namespace LiteView
{
    /// <summary>
    /// 本地玩家与帧事件的相对角色（命中反馈的过滤键——《命中反馈与伤害数字专项设计》§4.1）。
    ///
    /// **口径（用户裁决）**：伤害数字**只显示本地玩家造成/承受**——本枚举是"本地相关性"
    /// 的唯一判定面，消费者（伤害数字）按角色过滤；命中特效/音效对旁观事件同样可见（过滤不是
    /// 分发器的职责——它如实解析角色，裁决权在消费者）。
    ///
    /// 本文件**零引擎引用**（L1 经源链接直测伤害数字纯件——聚合/样式以本角色为键）；
    /// 携带 <see cref="UnityEngine"/> 类型的上下文/消费者接口在 <c>HitFeedback.cs</c>（Unity 侧独编）。
    /// </summary>
    public enum HitLocalRole : byte
    {
        /// <summary>旁观——事件与本地玩家无关（伤害数字滤掉；特效/音效照常）。</summary>
        Bystander = 0,

        /// <summary>造成——本地玩家是射手/击杀者（白色档）。</summary>
        Caused = 1,

        /// <summary>承受——本地玩家是命中目标/死者（红色档；自伤优先记承受）。</summary>
        Received = 2,
    }
}
