"""Generated-artifact contracts: uniform toolbox signature + deterministic regen.

Covers the 10 toolbox-owned text artifacts (plan v8 assumption 1) and the
content envelope's canonical manifest.

Pinned by this file (tests-first, implementation task T3):

- every artifact's leading signature block is <=3 lines, closes with ``>`` and
  contains ``toolbox/<tool>``, an ``input: ... sha256:<8>`` fingerprint line and
  a ``regen:`` line pointing at ``toolbox.py <tool>``; no timestamps;
- regeneration is byte-identical (idempotent);
- the sync-code fingerprint tracks the parsed ``[StateLayer]`` field model, not
  arbitrary source edits;
- the LuaKeys fingerprint tracks only the registry xlsx set
  (``gen_lua_keys.collect()``), so non-registry tables do not churn the head.

Battle.cs (protoc output), SimTrigTables.cs (inside the BuildHash closure) and
the Luban template outputs stay out of this contract (see the design doc).
"""

