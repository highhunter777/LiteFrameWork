# -*- coding: utf-8 -*-
"""Generated-artifact contracts: uniform signature + deterministic regeneration.

Covers the three generators we own (build-hash / sync-code / lua-keys) and the
content envelope's canonical manifest. Luban's own template output and the
randomized RSA signature are out of scope (see the generator toolbox design).
"""

import importlib.util
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))


def _load(module_name, relative):
    spec = importlib.util.spec_from_file_location(module_name, ROOT / relative)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


gen_candidate = _load("gen_candidate", "scripts/content/gen-candidate.py")
gen_luban = _load("gen_luban", "scripts/codegen/gen_luban.py")
gen_sync_code = _load("gen_sync_code", "scripts/codegen/gen_sync_code.py")

SYNC_OUTPUT = ROOT / "Assets" / "LiteSim" / "Core" / "Diagnostics" / "Generated" / "EntitySlot.Sync.g.cs"
GENERATED = {
    "Assets/LiteNet/Protocol/BuildHash.g.cs": "scripts/codegen/gen-build-hash.py",
    "Server/MetaServer/Host/BuildHash.g.cs": "scripts/codegen/gen-build-hash.py",
    "Assets/LiteSim/Core/Diagnostics/Generated/EntitySlot.Sync.g.cs": "scripts/codegen/gen_sync_code.py",
    "Assets/LiteGame/LuaBridge/Generated/LuaKeys.g.cs": "Luban/gen_lua_keys.py",
}


def signature_block(path):
    """Return the leading `//` signature block; it must close with `>`."""
    lines = []
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        if not line.startswith("//"):
            break
        lines.append(line)
        if line.rstrip().endswith(">"):
            break
    return "\n".join(lines)


class SignatureTests(unittest.TestCase):
    def test_every_generated_file_carries_the_same_signature_shape(self):
        for relative, generator in GENERATED.items():
            with self.subTest(artifact=relative):
                block = signature_block(ROOT / relative)
                self.assertTrue(block.startswith("// <auto-generated: "), block)
                self.assertIn(generator, block)
                self.assertIn("DO NOT EDIT", block)
                self.assertIn("源：", block)
                self.assertTrue(block.rstrip().endswith(">"), block)
                self.assertLessEqual(len(block.splitlines()), 3, block)


class IdempotenceTests(unittest.TestCase):
    def test_sync_code_regeneration_is_byte_identical(self):
        built = gen_sync_code.build()
        on_disk = SYNC_OUTPUT.read_bytes().decode("utf-8-sig")
        self.assertEqual(built, on_disk)
        self.assertIn("\r\n", built, "generated artifact keeps CRLF")

    def test_build_hash_constants_match_sources(self):
        result = subprocess.run(
            [sys.executable, str(ROOT / "scripts" / "codegen" / "gen-build-hash.py"), "--check"],
            cwd=ROOT, capture_output=True, text=True, timeout=120,
        )
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("CHECK OK", result.stdout)

    def test_luban_publish_copies_only_changed_files(self):
        with tempfile.TemporaryDirectory() as temp:
            source = Path(temp) / "stage"
            target = Path(temp) / "published"
            source.mkdir()
            target.mkdir()
            (source / "a.cs").write_text("class A {}\n", encoding="utf-8")

            gen_luban.publish(str(source), str(target), ".cs")
            first = (target / "a.cs").read_bytes()

            with mock.patch.object(gen_luban.shutil, "copyfile") as copyfile:
                gen_luban.publish(str(source), str(target), ".cs")
            copyfile.assert_not_called()
            self.assertEqual((target / "a.cs").read_bytes(), first)

    def test_candidate_manifest_is_deterministic(self):
        with tempfile.TemporaryDirectory() as temp:
            content = Path(temp) / "content"
            (content / "config").mkdir(parents=True)
            (content / "config" / "a.json").write_text("{}", encoding="utf-8")
            entries, skipped = gen_candidate.collect_entries(content)
            self.assertEqual(skipped, 0)

            args = dict(
                release_id="release-1", revision=7, platform="windows",
                created=1_760_000_000, expires=1_760_600_000, key_id="test-key",
            )
            first = gen_candidate.canonical_manifest(entries, **args)
            second = gen_candidate.canonical_manifest(entries, **args)
            self.assertEqual(first, second)
            self.assertIn('"Path":"config/a.json"', first)


if __name__ == "__main__":
    unittest.main()
