# -*- coding: utf-8 -*-
"""Environment restore check.

Missing BLOCKING items exit 1 and list every missing piece; WARN items do not
block. Mirrors the prior PowerShell check and adds the content-signing
cryptography dependency.
"""

import argparse
import importlib.util
import json
import re
import shutil
import subprocess
import sys
from importlib import metadata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from _common import EXIT_FAIL, EXIT_OK, configure_stdio, info, repo_root  # noqa: E402
from _unity_path import UnityPathError, resolve_unity_exe  # noqa: E402


def package_version(name):
    try:
        return metadata.version(name)
    except metadata.PackageNotFoundError:
        return None


def main(argv=None):
    parser = argparse.ArgumentParser(description="Environment restore check")
    parser.add_argument("--project-path", default=None)
    args = parser.parse_args(argv)
    configure_stdio()
    project = Path(args.project_path).resolve() if args.project_path else repo_root()
    ok, warnings, blocking = [], [], []

    def good(message):
        ok.append(message)

    def warn(message):
        warnings.append(message)

    def miss(message):
        blocking.append(message)

    info("env/restore", f"Restore check | project: {project}")

    # 1. Unity project settings & version
    toolchain_path = project / "scripts" / "gate" / "toolchain.json"
    expected = revision = None
    if toolchain_path.is_file():
        try:
            toolchain = json.loads(toolchain_path.read_text(encoding="utf-8"))
            unity = toolchain.get("unity") or {}
            expected = unity.get("version")
            revision = unity.get("revision")
        except Exception as exc:
            warn(f"toolchain.json parse failed: {exc}")
    if not expected:
        miss("toolchain.json unity.version missing (cannot verify editor identity)")

    version_path = project / "ProjectSettings" / "ProjectVersion.txt"
    if version_path.is_file():
        text = version_path.read_text(encoding="utf-8", errors="replace")
        version_match = re.search(r"m_EditorVersion:\s*(\S+)", text)
        version = version_match.group(1) if version_match else ""
        if expected and version == expected:
            good(f"Unity {version} (matches toolchain.json)")
        elif expected:
            miss(f"Unity version mismatch: got {version}, expected {expected} (scripts/gate/toolchain.json)")
        if revision:
            match = re.search(r"m_EditorVersionWithRevision:\s*\S+\s*\(([0-9a-fA-F]+)\)", text)
            if match and match.group(1) == revision:
                good(f"Unity revision {revision} (matches toolchain.json)")
            elif match:
                miss(f"Unity revision mismatch: got {match.group(1)}, expected {revision} (scripts/gate/toolchain.json)")
            else:
                warn("ProjectVersion.txt has no revision line; cannot verify toolchain.json unity.revision")
        if not (project / "ProjectSettings" / "ProjectSettings.asset").is_file():
            miss("ProjectSettings incomplete (not in repo; obtain from controlled source - see Docs/clone-restore guide)")
        else:
            good("ProjectSettings complete")
    else:
        miss("ProjectVersion.txt missing: ProjectSettings/ is not in the repo and must be provided (see Docs guide)")

    try:
        editor, source = resolve_unity_exe(project)
        good(f"Unity editor resolved: {editor} ({source})")
    except UnityPathError as exc:
        warn(f"Unity editor not resolved: {exc}")

    # 2. Dependency declarations
    manifest = project / "Packages" / "manifest.json"
    lock = project / "Packages" / "packages-lock.json"
    if not manifest.is_file():
        miss("Packages/manifest.json missing (must ship with repo)")
    else:
        try:
            dependencies = (json.loads(manifest.read_text(encoding="utf-8")).get("dependencies") or {})
            bad = []
            for name, value in dependencies.items():
                if not isinstance(value, str):
                    continue
                if value.startswith("file:") and re.match(r"file:([A-Za-z]:|/)", value):
                    bad.append(f"{name}={value}")
                if value.endswith(".git") or (".git" in value and not re.search(r"\.git#[0-9a-f]{40}", value)):
                    bad.append(f"{name}=floating git dep (pin commit)")
            if bad:
                miss("manifest has personal absolute paths or floating deps: " + "; ".join(bad))
            else:
                good(f"manifest.json reproducible ({len(dependencies)} deps, zero personal paths)")
        except Exception as exc:
            miss(f"manifest.json parse failed: {exc}")
    if not lock.is_file():
        warn("packages-lock.json missing (generated by Unity; commit before push)")
    else:
        good("packages-lock.json present")

    for package in ("com.tuyoogame.yooasset", "com.code-philosophy.luban"):
        package_json = project / "Packages" / package / "package.json"
        if package_json.is_file():
            good(f"vendored package present: {package}")
        else:
            miss(f"vendored package missing: Packages/{package} (must ship with repo)")

    # 3. Toolchain
    dotnet = shutil.which("dotnet")
    if dotnet:
        version = subprocess.run([dotnet, "--version"], capture_output=True, text=True, encoding="utf-8").stdout.strip()
        if version.startswith("8."):
            good(f".NET SDK {version}")
        else:
            warn(f".NET SDK {version} (L1/L3 target net8.0; prefer 8.x)")
    else:
        miss("dotnet SDK missing (required for L1/L3 tests and RoomServer; install .NET 8 SDK)")

    if sys.version_info >= (3, 10):
        openpyxl = package_version("openpyxl")
        if openpyxl:
            good(f"Python {sys.version.split()[0]} + openpyxl {openpyxl} (Luban chain)")
        else:
            miss("python missing openpyxl (pip install openpyxl - required by Luban/gen_lua_keys.py step 3)")
        cryptography = package_version("cryptography")
        if cryptography:
            good(f"cryptography {cryptography} (content signing)")
        else:
            miss("python missing cryptography (pip install cryptography - required by content signing)")
    else:
        warn(f"Python {sys.version.split()[0]} (gen_lua_keys.py needs >= 3.10)")

    if shutil.which("git"):
        good("git present")
    else:
        miss("git missing")

    # 4. Paid / restricted plugins
    sirenix = project / "Assets" / "Plugins" / "Sirenix"
    if sirenix.is_dir():
        odin = [path for path in sirenix.rglob("Sirenix.OdinInspector.Attributes.dll") if path.is_file()]
        if odin:
            good("Odin Inspector present (paid plugin, installed locally)")
        else:
            miss("Sirenix dir exists but Odin assemblies missing (reinstall Odin Inspector 4.0.2.3)")
    else:
        miss(
            "Odin Inspector missing: Assets/Plugins/Sirenix (per-seat paid, non-redistributable; "
            "install it yourself - see scripts/gate/toolchain.json paidOrRestrictedPlugins)"
        )

    if (project / "Assets" / "Plugins" / "Demigiant" / "DOTween").is_dir():
        good("DOTween present (free plugin, installed locally)")
    else:
        miss(
            "DOTween missing: Assets/Plugins/Demigiant/DOTween "
            "(LiteGame.UI references DOTween.Modules; install free version from Asset Store)"
        )
    if (project / "Assets" / "Plugins" / "UniTask").is_dir():
        good("UniTask present")
    else:
        miss("UniTask missing: Assets/Plugins/UniTask (runtime required; should ship with repo)")
    if (project / "Assets" / "Plugins" / "xlua.bundle").is_dir():
        good("xLua native plugin present")
    else:
        miss("xlua.bundle missing: Assets/Plugins/xlua.bundle (runtime required; should ship with repo)")

    # 5. Tracked UI/render assets
    if (project / "Assets" / "ShareResource" / "Fonts" / "NotoSansSC-Regular SDF.asset").is_file():
        good("TMP CJK font present (Assets/ShareResource/Fonts, tracked)")
    else:
        miss(
            "TMP CJK font missing: Assets/ShareResource/Fonts/NotoSansSC-Regular SDF.asset "
            "(tracked since 2026-10-13; incomplete checkout - see restore guide)"
        )
    if (project / "Assets" / "Settings" / "URP-Balanced.asset").is_file():
        good("URP pipeline assets present (Assets/Settings, tracked)")
    else:
        miss(
            "URP pipeline assets missing: Assets/Settings "
            "(tracked since 2026-10-13; ProjectSettings/GraphicsSettings references them by GUID - see restore guide)"
        )

    # 6. Content items (WARN)
    if (project / "Assets" / "Scenes" / "Boot.unity").is_file() or (
        project / "Assets" / "Scenes" / "TrainingGround.unity"
    ).is_file():
        good("At least one scene present (Boot.unity is tracked)")
    else:
        warn("Assets/Scenes missing - cannot run directly")
    if not shutil.which("java"):
        warn("JDK not detected - Android IL2CPP build (mobile) needs JDK 11 + Android SDK/NDK (not blocking Windows dev)")

    # Toolchain manifest / surfaces
    cli = project / "scripts" / "toolchain.py"
    if cli.is_file():
        result = subprocess.run(
            [sys.executable, str(cli), "check"], cwd=str(project), capture_output=True, text=True, encoding="utf-8"
        )
        if result.returncode != 0:
            tail = " ".join((result.stdout + result.stderr).splitlines()[-3:])
            warn(f"toolchain check failed: {tail}")
        else:
            good("toolchain check passed (manifest/docs/surfaces)")
    else:
        warn("toolchain CLI missing: scripts/toolchain.py (manifest/surface check skipped)")

    print("")
    for message in ok:
        print(f"  [OK]   {message}")
    for message in warnings:
        print(f"  [WARN] {message}")
    if blocking:
        print("")
        for message in blocking:
            print(f"  [MISS] {message}")
        print("")
        info("env/restore", f"Restore check FAILED: {len(blocking)} blocking item(s) - fix the list above and re-run")
        return EXIT_FAIL
    print("")
    info("env/restore", "Restore check PASSED: workspace can open / run L1,L3 / proceed to build")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
