#!/usr/bin/env python3
r"""Comment budget lint: XML doc blocks max 4 lines; plain block comments max 3 (type) / 2 (member).

Rules (AGENTS.md red line / 02-代码与修改规范 §1.4):
  C1 XML doc block (consecutive /// lines, tags included) <= 4 lines.
  C2 Plain block comment (// or /* */) attached to a declaration: type <= 3, member <= 2.
     Inline comments inside a method body are not counted.
  C3 Exempt: generated (*.g.cs, *.Generated.cs, Generated/), vendored/third-party, obj/bin/.dotnet.

Usage:
  python scripts/gate/comment-lint.py                  # incremental: working tree vs HEAD
  python scripts/gate/comment-lint.py --all            # full inventory (report only)
  python scripts/gate/comment-lint.py --all --strict   # full inventory, fail on violations
  python scripts/gate/comment-lint.py --base origin/main
  python scripts/gate/comment-lint.py --json out.json  # machine-readable list

Exit: 0 pass; 1 violations (incremental mode or --strict).
"""
import argparse
import json
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from _common import repo_root  # noqa: E402

SCAN_ROOTS = ('Assets', 'Packages', 'Server', 'Tests')
EXCLUDE = re.compile(
    r'(^|/)(obj|bin|\.dotnet|ThirdParty|ThirdPartyPkg|TextMesh Pro|MCPForUnity|Tests~)/'
    r'|com\.unity\.pipeline'
    r'|/(kcp2k|UniTask|UniRx|XLua|DOTween|Cinemachine)/',
    re.IGNORECASE)
GENERATED = re.compile(r'/Generated/|\.g\.cs$|\.Generated\.cs$|\.Designer\.cs$', re.IGNORECASE)
# 原始资源目录（非代码入库面）：只按 Assets 顶层锚定，避免误伤 Modules/Map 之类
ASSET_RAW = re.compile(r'^Assets/(Animation|Animator|Art|FX|Map|Model|Plugins|Resources|ThirdParty|TextMesh Pro)/', re.IGNORECASE)

XML_MAX = 4
TYPE_MAX = 3
MEMBER_MAX = 2

TYPE_DECL = re.compile(r'\b(class|interface|struct|enum|record|delegate)\s+[A-Za-z_]')
MEMBER_HINT = re.compile(r'\(|=>|\{\s*get\b')
EXEMPT_TAG = re.compile(r'^///\s*</?(param|typeparam|returns|exception)\b')


NOT_DECL = re.compile(r'^\s*(\[assembly|using\s|namespace\s|#|\}|$)')


def attached(lines, j: int) -> bool:
    k = j
    while k < len(lines) and not lines[k].strip():
        k += 1
    return k < len(lines) and not NOT_DECL.match(lines[k])


def classify(next_line: str) -> str:
    if TYPE_DECL.search(next_line):
        return 'type'
    if MEMBER_HINT.search(next_line):
        return 'member'
    return 'member'


def scan_file(path: Path):
    try:
        lines = path.read_text(encoding='utf-8', errors='replace').splitlines()
    except OSError:
        return []
    if any('<auto-generated' in l for l in lines[:4]):
        return []
    out = []
    i, n = 0, len(lines)
    while i < n:
        s = lines[i].strip()
        if s.startswith('///'):
            j = i
            while j < n and lines[j].strip().startswith('///'):
                j += 1
            if not attached(lines, j):
                i = j
                continue
            # <param>/<returns>/<exception>/<typeparam> 各一行不计入正文预算（规范 02 §1.11）
            counted = sum(1 for k in range(i, j)
                          if not EXEMPT_TAG.match(lines[k].strip()))
            if counted > XML_MAX:
                out.append((i + 1, 'xml', counted, XML_MAX))
            i = j
            continue
        if s.startswith('/*'):
            j = i
            while j < n and '*/' not in lines[j]:
                j += 1
            j = min(j + 1, n)
            k = j
            while k < n and not lines[k].strip():
                k += 1
            if k < n and attached(lines, j):
                kind = classify(lines[k])
                limit = TYPE_MAX if kind == 'type' else MEMBER_MAX
                if (j - i) > limit:
                    out.append((i + 1, kind, j - i, limit))
            i = j
            continue
        if s.startswith('//'):
            j = i
            while j < n and lines[j].strip().startswith('//') and not lines[j].strip().startswith('///'):
                j += 1
            k = j
            while k < n and not lines[k].strip():
                k += 1
            if k < n and attached(lines, j):
                kind = classify(lines[k])
                limit = TYPE_MAX if kind == 'type' else MEMBER_MAX
                if (j - i) > limit:
                    out.append((i + 1, kind, j - i, limit))
            i = j
            continue
        i += 1
    return out


def iter_files(root: Path):
    for base in SCAN_ROOTS:
        d = root / base
        if not d.is_dir():
            continue
        for p in d.rglob('*.cs'):
            rel = p.relative_to(root).as_posix()
            if base == 'Packages' and not rel.startswith('Packages/com.litegame.'):
                continue
            if ASSET_RAW.search(rel) or EXCLUDE.search(rel) or GENERATED.search(rel):
                continue
            yield p, rel


def changed_files(root: Path, base: str):
    try:
        out = subprocess.run(['git', '-C', str(root), 'diff', '--name-only', '--diff-filter=ACMR', base],
                             capture_output=True, text=True, encoding='utf-8', errors='replace')
        untracked = subprocess.run(['git', '-C', str(root), 'ls-files', '--others', '--exclude-standard'],
                                   capture_output=True, text=True, encoding='utf-8', errors='replace')
    except OSError:
        return None
    if out.returncode != 0:
        return None
    files = [x for x in out.stdout.splitlines() if x.strip()]
    files += [x for x in untracked.stdout.splitlines() if x.strip()]
    return [f.replace('\\', '/') for f in files if f.endswith('.cs')]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', default=None)
    ap.add_argument('--all', action='store_true')
    ap.add_argument('--base', default='HEAD')
    ap.add_argument('--strict', action='store_true')
    ap.add_argument('--json', default=None)
    ap.add_argument('--top', type=int, default=15)
    ap.add_argument('--max-print', type=int, default=40)
    args = ap.parse_args()

    root = Path(args.root).resolve() if args.root else repo_root()

    targets = None
    if not args.all:
        changed = changed_files(root, args.base)
        if changed is None:
            print('[quality/comment-lint] SKIP: git unavailable or bad base ' + args.base)
            return 0
        targets = set(changed)

    findings, scanned = [], 0
    for p, rel in iter_files(root):
        if targets is not None and rel not in targets:
            continue
        scanned += 1
        for line, kind, length, limit in scan_file(p):
            findings.append(dict(file=rel, line=line, kind=kind, lines=length, limit=limit))

    if args.json:
        Path(args.json).write_text(json.dumps(findings, ensure_ascii=False, indent=1), encoding='utf-8')

    for f in findings[:args.max_print]:
        print("[quality/comment-lint] FAIL: {file}:{line} {kind} {lines} > {limit} lines".format(**f))
    if len(findings) > args.max_print:
        print('[quality/comment-lint] ... %d more (use --json)' % (len(findings) - args.max_print))

    if findings:
        by_dir = Counter('/'.join(f['file'].split('/')[:3]) for f in findings)
        for d, c in by_dir.most_common(args.top):
            print('[quality/comment-lint]   %5d  %s' % (c, d))

    mode = 'all' if args.all else 'changed(vs %s)' % args.base
    failed = bool(findings) and ((not args.all) or args.strict)
    status = 'FAILED' if failed else ('REPORT' if args.all else 'OK')
    print('[quality/comment-lint] %s: %d violation(s), %d file(s) scanned (%s)'
          % (status, len(findings), scanned, mode))
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main())
