#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""AR2 改动单元上限：一个目录 = 一个命名空间 = 一个改动单元。

规则（客户端架构重构演进路线图 §3.2 / 规范 02 §1.12）：
  AR2-1 单元定义：直接包含 `.cs` 的目录（不递归）；子目录各自成单元。
  AR2-2 files  > 5    → 违规（该目录下直接存放的 .cs 数）。
  AR2-3 lines  > 600  → 违规（同上直接存放文件的总行数，物理行）。
  AR2-4 entry  != 1   → 违规；入口文件＝与目录同名的 `.cs`（`Arena/Arena.cs`），
       一个都没有＝missing，大小写重复＝duplicate。
  AR2-5 不纳入：生成物、随包第三方（Adapters/kcp2k）、obj/bin/Library/Temp。
  AR2-6 存量按基线棘轮：默认模式出现基线外的新违规单元即失败；--all 只普查；
       --update-baseline 重写基线但按「单元路径集合」判定，只允许缩小。
       棘轮判据是单元路径集合、不是计数：新目录即新键（缺入口文件几乎必然），
       所以「新建单元必须带入口文件」由棘轮本身强制，不靠放宽 entry 判据。

「0 个跨单元接口」本期只报告不判定（需要引用图，等程序集收敛/HCLR P2）：
统计 `Abstractions/` 目录下 interface-only 文件数与所在单元，输出为信息行。

用法：
  python scripts/gate/change-unit.py                # 对基线棘轮（本地/CI）
  python scripts/gate/change-unit.py --all          # 全量普查（报告，不红）
  python scripts/gate/change-unit.py --all --strict # 全量普查且违规即红
  python scripts/gate/change-unit.py --update-baseline
  python scripts/gate/change-unit.py --scope Assets/LiteGame/Modules/UI --all
  python scripts/gate/change-unit.py --json out.json

退出码：0 通过；1 有新违规（或 --strict 下普查有违规）。
"""
import argparse
import importlib.util
import json
import os
import re
import subprocess
import sys
from collections import Counter
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from _common import EXIT_FAIL, EXIT_OK, configure_stdio, info  # noqa: E402

TOOL = "quality/change-unit"
BASELINE_REL = Path("arch") / "change-unit-baseline.json"
MAX_FILES = 5
MAX_LINES = 600


def _ar1_code_roots():
    """AR2 与 AR1 同一作用域：直接复用 namespace-path.py 的 CODE_ROOTS 唯一来源。

    两份清单各自维护必然漂移，所以这里不复制条目，只读取 AR1 的分区表。
    """
    path = Path(__file__).resolve().parent / "namespace-path.py"
    spec = importlib.util.spec_from_file_location("_ar1_namespace_path_scope", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return tuple(entry["path"] for entry in module.CODE_ROOTS)


# 作用域＝AR1（namespace-path.py）的 CODE_ROOTS，逐条相同（客户端代码 + 共享包）。
UNIT_ROOTS = _ar1_code_roots()
SKIP_DIRS = {"obj", "bin", "__pycache__", "node_modules", "Library", "Temp", "Logs"}
VENDORED_PREFIXES = ("Packages/com.litegame.net/Adapters/kcp2k",)
GENERATED_SUFFIXES = (".g.cs", ".Generated.cs", ".Designer.cs")
BLOCK_COMMENT = re.compile(r"/\*.*?\*/", re.S)
LINE_COMMENT = re.compile(r"//[^\n]*")
TYPE_KEYWORD = re.compile(r"\b(interface|class|struct|enum|record|delegate)\b")


def rel_posix(path: Path, root: Path) -> str:
    return path.relative_to(root).as_posix()


def generated_by_content(text: str) -> bool:
    return "<auto-generated" in "\n".join(text.splitlines()[:5]).lower()


def in_scope(rel: str, scope: str) -> bool:
    return not scope or rel == scope or rel.startswith(scope + "/")


def iter_units(root: Path, scope: str = ""):
    """产出 (unit_rel, [(file_name, text)])；unit = 直接含 .cs 的目录。"""
    for base_rel in UNIT_ROOTS:
        base = root / base_rel
        if not base.is_dir():
            continue
        for dirpath, dirnames, filenames in os.walk(base):
            rel_dir = rel_posix(Path(dirpath), root)
            dirnames[:] = [d for d in dirnames
                           if d not in SKIP_DIRS and not d.startswith(".")
                           and not any((rel_dir + "/" + d).startswith(p)
                                       for p in VENDORED_PREFIXES)]
            if not in_scope(rel_dir, scope):
                continue
            files = []
            for name in filenames:
                if not name.endswith(".cs") or name.endswith(GENERATED_SUFFIXES):
                    continue
                if any((rel_dir + "/" + name).startswith(p) for p in VENDORED_PREFIXES):
                    continue
                try:
                    text = (Path(dirpath) / name).read_text(
                        encoding="utf-8-sig", errors="replace")
                except OSError:
                    continue
                if generated_by_content(text):
                    continue
                files.append((name, text))
            if files:
                yield rel_dir, files


def entry_state(unit: str, names) -> str:
    base = unit.rsplit("/", 1)[-1].lower()
    hits = [n for n in names if n[:-3].lower() == base]
    if not hits:
        return "missing"
    if len(hits) > 1:
        return "duplicate"
    return "ok"


def measure(unit: str, files):
    names = [name for name, _ in files]
    return {
        "files": len(files),
        "lines": sum(len(text.splitlines()) for _, text in files),
        "entry": entry_state(unit, names),
    }


def violations_of(record) -> list:
    out = []
    if record["files"] > MAX_FILES:
        out.append("files")
    if record["lines"] > MAX_LINES:
        out.append("lines")
    if record["entry"] != "ok":
        out.append("entry")
    return out


def scan(root: Path, scope: str = ""):
    units = {}
    for unit, files in iter_units(root, scope):
        record = measure(unit, files)
        record["violations"] = violations_of(record)
        units[unit] = record
    return units


def git_state(root: Path):
    """基线过期判据：生成时的 HEAD 与工作树是否脏。git 不可用时返回 (None, None)。"""
    try:
        head = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"],
                              capture_output=True, text=True, encoding="utf-8",
                              errors="replace")
        status = subprocess.run(["git", "-C", str(root), "status", "--porcelain"],
                                capture_output=True, text=True, encoding="utf-8",
                                errors="replace")
    except OSError:
        return None, None
    sha = head.stdout.strip() if head.returncode == 0 else None
    dirty = bool(status.stdout.strip()) if status.returncode == 0 else None
    return sha, dirty


def load_baseline(root: Path):
    path = root / BASELINE_REL
    if not path.is_file():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, json.JSONDecodeError) as exc:
        raise SystemExit(f"[{TOOL}] 基线不可读：{path} ({exc})")


def warn_if_provisional(baseline):
    """基线是脏树上生成的 ⇒ 可能是临时基线，树稳定后须重新生成。"""
    if baseline is not None and baseline.get("dirty") is True:
        print(f"[{TOOL}] WARN: 基线生成于脏树（gitHead={str(baseline.get('gitHead'))[:8]}，"
              "dirty=true）——可能是临时基线；树稳定后应重新生成，再用于棘轮")


def write_baseline(root: Path, units):
    violating = {u: units[u] for u in sorted(units) if units[u]["violations"]}
    head, dirty = git_state(root)
    payload = {
        "rule": "AR2 改动单元：目录 .cs <= 5、总行 <= 600、入口文件唯一且与目录同名；棘轮只减不增",
        "guard": "python scripts/gate/change-unit.py",
        "generator": "python scripts/gate/change-unit.py --update-baseline",
        "version": 1,
        "generatedAt": datetime.now().astimezone().isoformat(timespec="seconds"),
        # 基线过期判据：树稳定后重新生成，HEAD 变化或 dirty 由 true 变 false 即应刷新
        "gitHead": head,
        "dirty": dirty,
        "thresholds": {"files": MAX_FILES, "lines": MAX_LINES, "entry": "同名 .cs 唯一"},
        "scope": list(UNIT_ROOTS),
        "counts": {
            "units": len(units),
            "violatingUnits": len(violating),
            "files": sum(1 for r in violating.values() if "files" in r["violations"]),
            "lines": sum(1 for r in violating.values() if "lines" in r["violations"]),
            "entry": sum(1 for r in violating.values() if "entry" in r["violations"]),
        },
        "units": violating,
    }
    path = root / BASELINE_REL
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=1) + "\n",
                    encoding="utf-8", newline="\n")
    return path, payload["counts"]


def interface_only(text: str) -> bool:
    """只声明 interface 的文件（剥注释后看类型关键字集合）。粗判，够做报告。"""
    body = LINE_COMMENT.sub("", BLOCK_COMMENT.sub("", text))
    keywords = {m.group(1) for m in TYPE_KEYWORD.finditer(body)}
    return keywords == {"interface"}


def report_interface_only(units):
    total, by_unit = 0, []
    for unit in sorted(units):
        count = 0
        for name, text in iter_units_cached[unit]:
            if "Abstractions" in unit.split("/") and interface_only(text):
                count += 1
        if count:
            total += count
            by_unit.append((count, unit))
    info(TOOL, f"INFO（只报告，不判定）Abstractions/ 下 interface-only 文件：{total} 个，"
               f"分布于 {len(by_unit)} 个单元")
    for count, unit in sorted(by_unit, reverse=True)[:10]:
        print(f"[{TOOL}]   interface-only {count:3d}  {unit}")
    print(f"[{TOOL}]   「0 个跨单元接口」本期不判定：需引用图，等程序集收敛/HCLR P2")


iter_units_cached = {}


def print_survey(units, max_print: int):
    violating = {u: r for u, r in units.items() if r["violations"]}
    counts = Counter(kind for r in violating.values() for kind in r["violations"])
    info(TOOL, f"units={len(units)}; violating={len(violating)} "
               f"(files>5: {counts.get('files', 0)}, lines>600: {counts.get('lines', 0)}, "
               f"entry!=1: {counts.get('entry', 0)})")
    print(f"[{TOOL}]   top units by violation:")
    ranked = sorted(violating.items(),
                    key=lambda kv: (-len(kv[1]["violations"]), -kv[1]["lines"], kv[0]))
    for unit, record in ranked[:max_print]:
        print(f"[{TOOL}]   {','.join(record['violations']):<18} files={record['files']:2d} "
              f"lines={record['lines']:4d} entry={record['entry']:<9} {unit}")
    if len(ranked) > max_print:
        print(f"[{TOOL}]   ... {len(ranked) - max_print} more")

    # 最接近达标：优先「无违规」单元，没有则「只差入口文件」单元
    compliant = [(r, u) for u, r in units.items() if not r["violations"]]
    if compliant:
        picks = sorted(compliant, key=lambda ru: (-ru[0]["files"], -ru[0]["lines"], ru[1]))[:10]
        label = "已完全达标（files<=5 且 lines<=600 且入口唯一）"
    else:
        near = [(r, u) for u, r in units.items() if r["violations"] == ["entry"]]
        picks = sorted(near, key=lambda ru: (-ru[0]["files"], -ru[0]["lines"], ru[1]))[:10]
        label = "最接近达标（files/lines 已达标，只缺同名入口文件）"
    print(f"[{TOOL}]   {label}:")
    for record, unit in picks:
        print(f"[{TOOL}]   files={record['files']:2d} lines={record['lines']:4d} {unit}")


def main(argv=None) -> int:
    configure_stdio()
    ap = argparse.ArgumentParser(
        description="AR2：改动单元 <=5 文件 / <=600 行 / 入口文件与目录同名（基线棘轮）")
    ap.add_argument("--root", default=None, help="仓库根（默认脚本上两级）")
    ap.add_argument("--all", action="store_true", help="全量普查（忽略基线，报告模式）")
    ap.add_argument("--strict", action="store_true", help="配合 --all：有违规即红")
    ap.add_argument("--update-baseline", action="store_true",
                    help="按当前树收紧基线（只允许缩小；拒绝新增单元）")
    ap.add_argument("--scope", default="", help="只扫某个仓库相对子目录（调试/冷启动探针用）")
    ap.add_argument("--json", default=None, help="违规单元清单落盘")
    ap.add_argument("--max-print", type=int, default=20)
    args = ap.parse_args(argv)

    root = Path(args.root).resolve() if args.root else Path(__file__).resolve().parents[2]
    scope = args.scope.replace("\\", "/").strip("/")

    # 缓存单元文件内容，report_interface_only 复用，避免二次读盘
    units = {}
    for unit, files in iter_units(root, scope):
        record = measure(unit, files)
        record["violations"] = violations_of(record)
        units[unit] = record
        iter_units_cached[unit] = files

    baseline = load_baseline(root)
    warn_if_provisional(baseline)
    violating = {u for u, r in units.items() if r["violations"]}

    if args.update_baseline:
        if baseline is not None:
            old = set((baseline.get("units") or {}).keys())
            added = violating - old
            if added:
                for unit in sorted(added)[:args.max_print]:
                    record = units[unit]
                    print(f"[{TOOL}] REFUSE: 新违规单元 {unit} "
                          f"({','.join(record['violations'])})")
                print(f"[{TOOL}] REFUSED: {len(added)} 个新单元，基线只允许缩小，未写入"
                      "（若旧基线是脏树上的临时基线，先删掉基线文件再生成）")
                return EXIT_FAIL
        path, counts = write_baseline(root, units)
        head, dirty = git_state(root)
        info(TOOL, f"baseline updated: {rel_posix(path, root)} "
                   f"({counts['violatingUnits']} unit(s) of {counts['units']}, "
                   f"gitHead={str(head)[:8]} dirty={dirty})")
        return EXIT_OK

    if args.json:
        Path(args.json).write_text(
            json.dumps([{"unit": u, **units[u]} for u in sorted(violating)],
                       ensure_ascii=False, indent=1) + "\n", encoding="utf-8")

    if args.all:
        print_survey(units, args.max_print)
        report_interface_only(units)
        return EXIT_FAIL if (args.strict and violating) else EXIT_OK

    if baseline is None:
        info(TOOL, f"基线缺失：{BASELINE_REL.as_posix()}；先跑 --update-baseline 建立现状")
        print_survey(units, args.max_print)
        return EXIT_FAIL

    old_units = baseline.get("units") or {}
    added = sorted(violating - set(old_units))
    if added:
        for unit in added[:args.max_print]:
            record = units[unit]
            print(f"[{TOOL}] FAIL: {unit} ({','.join(record['violations'])}) "
                  f"files={record['files']} lines={record['lines']} entry={record['entry']}")
        if len(added) > args.max_print:
            print(f"[{TOOL}] ... {len(added) - args.max_print} more (use --json)")
        info(TOOL, f"新增 {len(added)} 个违规单元")
        return EXIT_FAIL

    # 单元路径集合不变时，指标回涨只提醒（本守卫判据＝单元路径集合，见任务口径）
    growth = []
    for unit, before in old_units.items():
        now = units.get(unit)
        if not now:
            continue
        if now["files"] > before.get("files", 0) or now["lines"] > before.get("lines", 0):
            growth.append((unit, before, now))
    for unit, before, now in growth[:10]:
        print(f"[{TOOL}] WARN: {unit} 指标回涨 files {before.get('files')}->{now['files']} "
              f"lines {before.get('lines')}->{now['lines']}（基线内单元，棘轮只管新增单元）")

    resolved = sorted(set(old_units) - violating)
    for unit in resolved[:10]:
        print(f"[{TOOL}] INFO: 已解决（可 --update-baseline 收紧）：{unit}")
    info(TOOL, f"OK: {len(units)} unit(s) scanned, {len(old_units)} baselined, no new unit")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
