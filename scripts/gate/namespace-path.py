#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""AR1 路径 = 命名空间：代码目录路径与命名空间路径逐段相等（零例外）。

规则（客户端架构重构演进路线图 §3.4 / 规范 02 §1.13）：
  AR1-1 文件所在目录按「代码根 → 命名空间前缀」映射后，剩余目录段必须逐段等于
        文件内第一个 namespace 声明；多命名空间文件取第一个（本版只判第一个，
        第二个命名空间本期不判）。
  AR1-2 无 namespace 声明的文件单独计一类违规（不自带命名空间＝身份不明）。
  AR1-3 目录名黑名单：Abstractions / SubModules / Impl / Interfaces 计入违规；
        Services 因存量规模大（83 个目录 / 222 个文件）本期只报不计基线，
        随收敛线并回单元后再转判定（见报告）。
  AR1-4 作用域＝客户端代码 + 共享包（规范 02 §1.12「作用域」条）：
        Assets/{LiteGame,LiteCodeGen,LiteTesting,Tests} 与
        Packages/com.litegame.{framework,sim,net,sync}；Server/、根 Tests/、
        Assets/RoomServer/ 暂不纳入（与 dir-flat-lint.py 的 SCOPE_ROOTS 同一口径）。
        另不纳入：Assets/ThirdParty、随包第三方（Adapters/kcp2k）、obj/bin/Library/
        Temp、生成物（*.g.cs、*.Generated.cs、*.Designer.cs、<auto-generated>）。
  AR1-5 存量按基线棘轮：默认模式出现基线外的新违规即失败；--all 只普查；
        --update-baseline 重写基线但只允许缩小（新集合必须是旧集合的子集）。

映射表 CODE_ROOTS 是唯一的分区来源：改目录形状只改这张表，不改判定逻辑。
`containers` 是「打包容器层」：位于代码根之下第一层的 Runtime/Editor/Scripts
不参与命名空间（Unity 包布局要求），其余目录段一律参与。

用法：
  python scripts/gate/namespace-path.py                     # 对基线棘轮（本地/CI）
  python scripts/gate/namespace-path.py --all               # 全量普查（报告，不红）
  python scripts/gate/namespace-path.py --all --strict      # 全量普查且违规即红
  python scripts/gate/namespace-path.py --update-baseline   # 基线收紧（只减不增）
  python scripts/gate/namespace-path.py --scope Assets/LiteGame/Modules/UI --all
  python scripts/gate/namespace-path.py --json out.json

退出码：0 通过；1 有新违规（或 --strict 下普查有违规）；2 用法错误。
"""
import argparse
import json
import os
import re
import subprocess
import sys
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from _common import EXIT_FAIL, EXIT_OK, configure_stdio, info  # noqa: E402

TOOL = "quality/namespace-path"
BASELINE_REL = Path("arch") / "namespace-path-baseline.json"

# ---------------------------------------------------------------- 配置（唯一分区来源）
# path：仓库相对路径（代码根）；ns：该根对应的命名空间前缀；
# containers：该根之下第一层不参与命名空间的目录名（Unity 打包容器）。
# 作用域＝客户端代码 + 共享包（规范 02 §1.12）：新增/移除代码根时同步改
# scripts/gate/dir-flat-lint.py 的 SCOPE_ROOTS 与该规范条文。
# 暂不纳入（on purpose）：Server/、根 Tests/、Assets/RoomServer/。
CODE_ROOTS = (
    {"path": "Assets/LiteGame", "ns": "LiteGame", "containers": ()},
    {"path": "Assets/LiteCodeGen", "ns": "LiteCodeGen", "containers": ("Runtime",)},
    {"path": "Assets/LiteTesting", "ns": "LiteTesting", "containers": ("Runtime", "Editor")},
    {"path": "Assets/Tests", "ns": "LiteGame.Tests", "containers": ()},
    {"path": "Packages/com.litegame.framework", "ns": "LiteFramework",
     "containers": ("Runtime", "Editor")},
    {"path": "Packages/com.litegame.sim", "ns": "LiteSim", "containers": ("Scripts",)},
    {"path": "Packages/com.litegame.net", "ns": "LiteNet", "containers": ()},
    {"path": "Packages/com.litegame.sync", "ns": "LiteSync", "containers": ()},
)
SKIP_DIRS = {"obj", "bin", "__pycache__", "node_modules", "Library", "Temp", "Logs"}
VENDORED_PREFIXES = ("Packages/com.litegame.net/Adapters/kcp2k",)
# 目录名黑名单（计入基线）与只报不计（存量过大 / 随收敛线并回）。
DIR_NAME_BLACKLIST = ("Abstractions", "SubModules", "Impl", "Interfaces")
DIR_NAME_REPORT_ONLY = ("Services",)
# 规范 02 §1.12 同样禁止的无意图目录；本版只报不判（未列入本单）。
NO_INTENT_REPORT_ONLY = ("Core", "Common", "Utils")
GENERATED_SUFFIXES = (".g.cs", ".Generated.cs", ".Designer.cs")
NS_DECL = re.compile(r"^namespace\s+([A-Za-z_][A-Za-z0-9_.]*)\s*[;{]?")
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
BLOCK_COMMENT = re.compile(r"/\*.*?\*/", re.S)

KIND_LABELS = {
    "namespace": "命名空间与目录不逐段相等",
    "no-namespace": "无 namespace 声明",
    "dir-name": "目录名黑名单",
    "path-segment": "目录段不是合法标识符",
}


def rel_posix(path: Path, root: Path) -> str:
    return path.relative_to(root).as_posix()


def generated_by_content(text: str) -> bool:
    return "<auto-generated" in "\n".join(text.splitlines()[:5]).lower()


def first_namespace(text: str):
    """取文件第一个 namespace 声明；块注释先剥掉，行注释整行跳过（够用的启发式）。"""
    stripped = BLOCK_COMMENT.sub("", text)
    for line in stripped.splitlines():
        s = line.strip()
        if not s or s.startswith("//"):
            continue
        m = NS_DECL.match(s)
        if m:
            return m.group(1)
    return None


def match_root(rel_file: str):
    """最长前缀匹配代码根；没匹配到返回 None（正常不会发生，walk 从根出发）。"""
    best = None
    for entry in CODE_ROOTS:
        base = entry["path"]
        if rel_file == base or rel_file.startswith(base + "/"):
            if best is None or len(base) > len(best["path"]):
                best = entry
    return best


def split_dir(rel_file: str):
    parts = rel_file.split("/")
    return "/".join(parts[:-1])


def expected_namespace(rel_file: str, entry):
    """返回 (expected, bad_segment)。bad_segment 非空表示目录段无法映射成命名空间。"""
    rel_dir = split_dir(rel_file)
    tail = rel_dir[len(entry["path"]):].lstrip("/")
    segments = [s for s in tail.split("/") if s]
    if segments and segments[0] in entry["containers"]:
        segments = segments[1:]
    for seg in segments:
        if not IDENT.match(seg):
            return None, seg
    if not segments:
        return entry["ns"], None
    return ".".join([entry["ns"]] + segments), None


def iter_code_files(root: Path):
    """产出 (abs_path, rel_file)。只走 CODE_ROOTS，按配置剪枝。"""
    for entry in CODE_ROOTS:
        base = root / entry["path"]
        if not base.is_dir():
            continue
        for dirpath, dirnames, filenames in os.walk(base):
            rel_dir = rel_posix(Path(dirpath), root)
            dirnames[:] = [d for d in dirnames
                           if d not in SKIP_DIRS and not d.startswith(".")
                           and not any((rel_dir + "/" + d).startswith(p) or
                                       (rel_dir + "/" + d) == p for p in VENDORED_PREFIXES)]
            for name in filenames:
                if not name.endswith(".cs") or name.endswith(GENERATED_SUFFIXES):
                    continue
                rel_file = rel_dir + "/" + name
                if any(rel_file.startswith(p) for p in VENDORED_PREFIXES):
                    continue
                yield Path(dirpath) / name, rel_file


def item_key(item):
    if item["kind"] in ("dir-name", "path-segment"):
        return (item["kind"], item["file"], item["actual"])
    return (item["kind"], item["file"])


def scan(root: Path, scope: str = ""):
    items, scanned = [], 0
    dir_name_seen, no_intent = set(), Counter()
    for path, rel_file in iter_code_files(root):
        if scope and rel_file != scope and not rel_file.startswith(scope + "/"):
            continue
        scanned += 1
        try:
            text = path.read_text(encoding="utf-8-sig", errors="replace")
        except OSError as exc:  # 读不动就按身份不明计，不静默跳过
            items.append({"kind": "no-namespace", "file": rel_file,
                          "expected": "", "actual": f"<unreadable: {exc}>"})
            continue
        if generated_by_content(text):
            scanned -= 1
            continue

        # 目录段黑名单（按目录去重；只报的名字单独计数）
        rel_dir = split_dir(rel_file)
        segments = rel_dir.split("/")
        for index, seg in enumerate(segments):
            if seg in DIR_NAME_REPORT_ONLY:
                no_intent["dir:" + seg] += 1
                continue
            if seg in NO_INTENT_REPORT_ONLY:
                no_intent["dir:" + seg] += 1
                continue
            if seg in DIR_NAME_BLACKLIST:
                dir_path = "/".join(segments[:index + 1])
                if (dir_path, seg) not in dir_name_seen:
                    dir_name_seen.add((dir_path, seg))
                    items.append({"kind": "dir-name", "file": dir_path,
                                  "expected": "（目录名不得为技术层名）", "actual": seg})

        entry = match_root(rel_file)
        if entry is None:
            items.append({"kind": "namespace", "file": rel_file,
                          "expected": "（文件不在已配置代码根内）", "actual": ""})
            continue
        expected, bad = expected_namespace(rel_file, entry)
        if bad is not None:
            items.append({"kind": "path-segment", "file": rel_file,
                          "expected": "（目录段须为合法 C# 标识符）", "actual": bad})
            continue
        actual = first_namespace(text)
        if actual is None:
            items.append({"kind": "no-namespace", "file": rel_file,
                          "expected": expected, "actual": ""})
        elif actual != expected:
            items.append({"kind": "namespace", "file": rel_file,
                          "expected": expected, "actual": actual})
    return items, scanned, no_intent


def git_state(root: Path):
    """基线过期判据：生成时的 HEAD 与工作树是否脏。git 不可用时返回 (None, None)。"""
    try:
        head = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"],
                              capture_output=True, text=True, encoding="utf-8",
                              errors="replace")
        status = subprocess.run(["git", "-C", str(root), "status", "--porcelain"],
                                capture_output=True, text=True, encoding="utf-8",
                                errors="replace")
    except OSError:
        return None, None
    sha = head.stdout.strip() if head.returncode == 0 else None
    dirty = None
    if status.returncode == 0:
        # 基线文件自身的改动不代表源码变化：重采一份基线不应让另一份被记成脏树
        changed = [ln for ln in status.stdout.splitlines() if "-baseline.json" not in ln]
        dirty = bool(changed)
    return sha, dirty


def load_baseline(root: Path):
    path = root / BASELINE_REL
    if not path.is_file():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, json.JSONDecodeError) as exc:
        raise SystemExit(f"[{TOOL}] 基线不可读：{path} ({exc})")
    return data


def warn_if_provisional(baseline):
    """基线是脏树上生成的 ⇒ 可能是临时基线，树稳定后须重新生成。"""
    if baseline is not None and baseline.get("dirty") is True:
        print(f"[{TOOL}] WARN: 基线生成于脏树（gitHead={str(baseline.get('gitHead'))[:8]}，"
              "dirty=true）——可能是临时基线；树稳定后应重新生成，再用于棘轮")


def write_baseline(root: Path, items, scanned: int, no_intent):
    counts = Counter(item["kind"] for item in items)
    head, dirty = git_state(root)
    payload = {
        "rule": "AR1 路径 = 命名空间：目录逐段等于 namespace（零例外）；存量棘轮只减不增",
        "guard": "python scripts/gate/namespace-path.py",
        "generator": "python scripts/gate/namespace-path.py --update-baseline",
        "version": 1,
        "generatedAt": datetime.now().astimezone().isoformat(timespec="seconds"),
        # 基线过期判据：树稳定后重新生成，HEAD 变化或 dirty 由 true 变 false 即应刷新
        "gitHead": head,
        "dirty": dirty,
        "scope": [entry["path"] for entry in CODE_ROOTS],
        "dirNameReportOnly": list(DIR_NAME_REPORT_ONLY),
        "noIntentReportOnly": {name[4:]: count for name, count in no_intent.items()},
        "counts": {"filesScanned": scanned, "total": len(items),
                   "namespace": counts.get("namespace", 0),
                   "no-namespace": counts.get("no-namespace", 0),
                   "dir-name": counts.get("dir-name", 0),
                   "path-segment": counts.get("path-segment", 0)},
        "items": sorted(items, key=lambda i: (i["kind"], i["file"], i["actual"])),
    }
    path = root / BASELINE_REL
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=1) + "\n",
                    encoding="utf-8", newline="\n")
    return path, counts


def print_summary(items, scanned, no_intent):
    counts = Counter(item["kind"] for item in items)
    info(TOOL, f"scanned {scanned} file(s); {len(items)} violation(s): "
               f"ns={counts.get('namespace', 0)} no-ns={counts.get('no-namespace', 0)} "
               f"dir-name={counts.get('dir-name', 0)} path-seg={counts.get('path-segment', 0)}")
    # 违规按目录的 Top 10
    by_dir = Counter(split_dir(item["file"]) if item["kind"] != "dir-name" else item["file"]
                     for item in items)
    for rel_dir, count in by_dir.most_common(10):
        print(f"[{TOOL}]   {count:4d}  {rel_dir}")
    if len(by_dir) > 10:
        print(f"[{TOOL}]   ... {len(by_dir) - 10} more dir(s)")
    # T3 代理指标：命名空间比目录浅（即 namespace 装了多份目录的文件）
    shallow = Counter()
    for item in items:
        if item["kind"] == "namespace" and item["actual"] and \
                item["expected"].startswith(item["actual"] + "."):
            shallow[item["actual"]] += 1
    for ns, count in shallow.most_common(5):
        print(f"[{TOOL}]   shallow-ns {count:4d}  {ns}")
    for name, count in no_intent.most_common():
        print(f"[{TOOL}]   INFO report-only {name[4:]}: 出现于 {count} 个文件路径（不计基线）")


def main(argv=None) -> int:
    configure_stdio()
    ap = argparse.ArgumentParser(
        description="AR1：代码目录路径必须逐段等于命名空间（基线棘轮，只减不增）")
    ap.add_argument("--root", default=None, help="仓库根（默认脚本上两级）")
    ap.add_argument("--all", action="store_true", help="全量普查（忽略基线，报告模式）")
    ap.add_argument("--strict", action="store_true", help="配合 --all：有违规即红")
    ap.add_argument("--update-baseline", action="store_true",
                    help="按当前树收紧基线（只允许缩小；拒绝新增）")
    ap.add_argument("--scope", default="", help="只扫某个仓库相对子目录（调试/冷启动探针用）")
    ap.add_argument("--json", default=None, help="违规清单落盘")
    ap.add_argument("--max-print", type=int, default=25)
    args = ap.parse_args(argv)

    root = Path(args.root).resolve() if args.root else Path(__file__).resolve().parents[2]
    scope = args.scope.replace("\\", "/").strip("/")
    items, scanned, no_intent = scan(root, scope)
    baseline = load_baseline(root)
    warn_if_provisional(baseline)

    if args.update_baseline:
        if baseline is not None:
            old_keys = {item_key(i) for i in baseline.get("items") or []}
            new_keys = {item_key(i) for i in items} - old_keys
            if new_keys:
                for key in sorted(new_keys)[:args.max_print]:
                    print(f"[{TOOL}] REFUSE: 新违规不在旧基线内：{key[0]} {key[1]}"
                          + (f" ({key[2]})" if len(key) > 2 else ""))
                print(f"[{TOOL}] REFUSED: {len(new_keys)} 条新违规，基线只允许缩小，未写入"
                      "（先修掉或确认规则变更；若旧基线是脏树上的临时基线，"
                      "先删掉基线文件再生成）")
                return EXIT_FAIL
        path, counts = write_baseline(root, items, scanned, no_intent)
        head, dirty = git_state(root)
        info(TOOL, f"baseline updated: {rel_posix(path, root)} "
                   f"({counts.get('namespace', 0) + counts.get('no-namespace', 0) + counts.get('dir-name', 0) + counts.get('path-segment', 0)}"
                   f" item(s), {scanned} file(s) scanned, gitHead={str(head)[:8]} dirty={dirty})")
        return EXIT_OK

    if args.json:
        Path(args.json).write_text(json.dumps(items, ensure_ascii=False, indent=1) + "\n",
                                   encoding="utf-8")

    if args.all:
        print_summary(items, scanned, no_intent)
        return EXIT_FAIL if (args.strict and items) else EXIT_OK

    if baseline is None:
        info(TOOL, f"基线缺失：{BASELINE_REL.as_posix()}；先跑 --update-baseline 建立现状")
        print_summary(items, scanned, no_intent)
        return EXIT_FAIL

    old_keys = {item_key(i) for i in baseline.get("items") or []}
    new_items = [i for i in items if item_key(i) not in old_keys]
    current_keys = {item_key(i) for i in items}
    resolved = sorted(old_keys - current_keys, key=lambda k: (k[0], k[1]))

    if new_items:
        counts = Counter(i["kind"] for i in new_items)
        for item in new_items[:args.max_print]:
            if item["kind"] == "namespace":
                print(f"[{TOOL}] FAIL: {item['file']} 期望 {item['expected']} "
                      f"实际 {item['actual']}")
            elif item["kind"] == "no-namespace":
                print(f"[{TOOL}] FAIL: {item['file']} 无 namespace（期望 {item['expected']}）")
            else:
                print(f"[{TOOL}] FAIL: {item['file']} {KIND_LABELS[item['kind']]}："
                      f"{item['actual']}")
        if len(new_items) > args.max_print:
            print(f"[{TOOL}] ... {len(new_items) - args.max_print} more (use --json)")
        info(TOOL, f"新增 {len(new_items)} 条：ns={counts.get('namespace', 0)} "
                   f"no-ns={counts.get('no-namespace', 0)} "
                   f"dir-name={counts.get('dir-name', 0)} "
                   f"path-seg={counts.get('path-segment', 0)}")
        return EXIT_FAIL

    for key in resolved[:10]:
        print(f"[{TOOL}] INFO: 已解决（可 --update-baseline 收紧）：{key[0]} {key[1]}"
              + (f" ({key[2]})" if len(key) > 2 else ""))
    info(TOOL, f"OK: {scanned} file(s) scanned, {len(items)} baselined violation(s), no growth")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
