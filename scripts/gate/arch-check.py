import sys
from pathlib import Path
from uuid import NAMESPACE_URL, uuid5

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from _common import EXIT_FAIL, EXIT_OK, configure_stdio, fail, info, repo_root  # noqa: E402

MODEL_REL = Path("arch") / "units.json"
LEGACY_TIERS_REL = Path("scripts") / "content" / "module-tiers.json"
SCAN_TARGETS_REL = Path("Assets") / "Tools" / "DisciplineScanner" / "Scripts" / "ScanTargets.cs"
SCAN_GENERATED_REL = Path("Assets") / "Tools" / "DisciplineScanner" / "Scripts" / "ScanTargets.Generated.cs"
CLIENT_ROOTS = (
    "Packages/com.litegame.framework",
    "Assets/LiteGame",
    "Packages/com.litegame.sim",
    "Packages/com.litegame.net",
    "Packages/com.litegame.sync",
    "Assets/LiteCodeGen",
)
VALID_BUCKET_KINDS = ("dotnet", "unity")
VALID_LANES = ("L1", "L2", "L3")
REQUIRED_TIERS = {"base", "script", "data"}
GENERATED_HEADER = (
    "// <auto-generated>\n"
    "// 生成物，禁手改：python scripts/gate/arch-check.py --write\n"
    "// 来源：arch/units.json\n"
    "// </auto-generated>\n"
)


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8-sig")


def load_model(project: Path) -> dict:
    path = project / MODEL_REL
    if not path.is_file():
        raise SystemExit(f"arch-check: 缺模型 {MODEL_REL.as_posix()}（先补齐 arch/units.json）")
    return json.loads(read_text(path))


def read_asmdef(path: Path) -> dict:
    return json.loads(read_text(path))


def collect_groups(project: Path) -> dict[str, list[str]]:
    setting = project / "Assets" / "BundleCollectorSetting.asset"
    if not setting.is_file():
        raise SystemExit("arch-check: 缺 Assets/BundleCollectorSetting.asset")
    result: dict[str, list[str]] = {}
    current = None
    for raw in read_text(setting).splitlines():
        line = raw.strip()
        group = re.match(r"^- GroupName:\s*([A-Za-z0-9_]+)", line)
        if group:
            current = group.group(1)
            result.setdefault(current, [])
            continue
        path = re.match(r"^- CollectPath:\s*(\S+)", line)
        if path and current:
            result[current].append(path.group(1))
    return result


def solution_projects(project: Path) -> set[str]:
    slnx = project / "Tests" / "Tests.slnx"
    if not slnx.is_file():
        return set()
    import xml.etree.ElementTree as ET

    result = set()
    root = ET.parse(slnx).getroot()
    for item in root.iter():
        if item.tag.rsplit("}", 1)[-1] != "Project":
            continue
        value = item.attrib.get("Path", "")
        if value:
            candidate = (slnx.parent / value).resolve()
            result.add(candidate.as_posix())
    return result


def scan_rule_names(project: Path) -> tuple[set[str], set[str]]:
    text = read_text(project / SCAN_TARGETS_REL)
    rules = set(re.findall(r"public\s+static\s+readonly\s+LintRule\[\]\s+(\w+)", text))
    excludes = set(re.findall(r"public\s+static\s+readonly\s+string\[\]\s+(\w+)", text))
    return rules, excludes


def module_units(model: dict) -> list[dict]:
    result = []
    for unit in model.get("units", []):
        path = unit.get("path", "")
        if path in ("Assets/LiteGame/Core", "Assets/LiteGame/App", "Assets/LiteGame/Bootstrap"):
            result.append(unit)
        elif path.startswith("Assets/LiteGame/Modules/") and len(path.split("/")) == 4:
            result.append(unit)
    return result


def validate_model(project: Path, model: dict) -> list[str]:
    errors: list[str] = []
    if model.get("version") != 1:
        errors.append("version 必须为 1")
    tiers = model.get("tiers") or []
    if set(tiers) != REQUIRED_TIERS or len(tiers) != len(REQUIRED_TIERS):
        errors.append("tiers 必须恰为 base/script/data")

    layers = model.get("layers") or []
    if not layers:
        errors.append("layers 不能为空")
    layer_by_id = {}
    for layer in layers:
        layer_id = layer.get("id")
        if not layer_id or layer_id in layer_by_id:
            errors.append(f"layer id 缺失或重复：{layer_id}")
            continue
        if not isinstance(layer.get("rank"), int):
            errors.append(f"layer {layer_id} 缺整数 rank")
        layer_by_id[layer_id] = layer
    ordered_layers = sorted(layers, key=lambda item: item.get("rank", 0))
    for index, layer in enumerate(ordered_layers):
        if index and layer["rank"] <= ordered_layers[index - 1]["rank"]:
            errors.append(f"layer rank 非严格递增：{layer['id']}")
        if not layer.get("name"):
            errors.append(f"layer {layer.get('id')} 缺 name")

    buckets = model.get("testBuckets") or {}
    for bucket_id, bucket in buckets.items():
        if bucket.get("kind") not in VALID_BUCKET_KINDS:
            errors.append(f"测试桶 {bucket_id} kind 非法：{bucket.get('kind')}")
        if bucket.get("lane") not in VALID_LANES:
            errors.append(f"测试桶 {bucket_id} lane 非法：{bucket.get('lane')}")
        path = project / bucket.get("path", "")
        if not path.exists():
            errors.append(f"测试桶 {bucket_id} 路径不存在：{bucket.get('path')}")
    dotnet_projects = solution_projects(project)
    for bucket_id, bucket in buckets.items():
        if bucket.get("kind") == "dotnet":
            resolved = (project / bucket.get("path", "")).resolve().as_posix()
            if resolved not in dotnet_projects:
                errors.append(f"测试桶 {bucket_id} 未登记在 Tests/Tests.slnx")

    external = model.get("externalAssemblies") or []
    external_names = set()
    for item in external:
        name = item.get("name")
        if not name or name in external_names:
            errors.append(f"外部程序集名缺失或重复：{name}")
            continue
        external_names.add(name)
        if not item.get("reason"):
            errors.append(f"外部程序集 {name} 缺 reason")

    units = model.get("units") or []
    if not units:
        errors.append("units 不能为空")
    by_id: dict[str, dict] = {}
    by_asmdef: dict[str, dict] = {}
    for unit in units:
        unit_id = unit.get("id")
        if not unit_id:
            errors.append("unit 缺 id")
            continue
        if unit_id in by_id:
            errors.append(f"unit id 重复：{unit_id}")
            continue
        by_id[unit_id] = unit
        asmdef = unit.get("asmdef", "")
        if asmdef in by_asmdef:
            errors.append(f"asmdef 被重复登记：{asmdef}")
        by_asmdef[asmdef] = unit

    ranks = {unit_id: unit.get("rank") for unit_id, unit in by_id.items()}
    for unit_id, unit in by_id.items():
        asmdef_path = project / unit.get("asmdef", "")
        if not asmdef_path.is_file():
            errors.append(f"{unit_id} 的 asmdef 不存在：{unit.get('asmdef')}")
            continue
        if Path(unit.get("path", "")).as_posix() != asmdef_path.parent.relative_to(project).as_posix():
            errors.append(f"{unit_id} 的 path 与 asmdef 目录不一致：{unit.get('path')}")
        actual = read_asmdef(asmdef_path)
        if actual.get("name") != unit_id:
            errors.append(f"{unit_id} 的 asmdef name 不一致：{actual.get('name')}")
        if bool(actual.get("noEngineReferences", False)) != bool(unit.get("noEngine", False)):
            errors.append(f"{unit_id} 的 noEngine 与模型不一致（asmdef={actual.get('noEngineReferences', False)}）")
        actual_constraints = actual.get("defineConstraints", []) or []
        if list(actual_constraints) != list(unit.get("defineConstraints", []) or []):
            errors.append(f"{unit_id} 的 defineConstraints 与模型不一致")

        actual_refs = list(actual.get("references", []) or [])
        if len(actual_refs) != len(set(actual_refs)):
            errors.append(f"{unit_id} 的 asmdef references 有重复项")
        model_refs = list(unit.get("references", []) or [])
        if len(model_refs) != len(set(model_refs)):
            errors.append(f"{unit_id} 的模型 references 有重复项")
        if set(actual_refs) != set(model_refs):
            missing = sorted(set(actual_refs) - set(model_refs))
            stale = sorted(set(model_refs) - set(actual_refs))
            if missing:
                errors.append(f"{unit_id} 有未登记的引用：{', '.join(missing)}")
            if stale:
                errors.append(f"{unit_id} 的模型登记了不存在的引用：{', '.join(stale)}")

        layer_id = unit.get("layer")
        if layer_id not in layer_by_id:
            errors.append(f"{unit_id} 的 layer 未知：{layer_id}")
            continue
        rank = unit.get("rank")
        if not isinstance(rank, int):
            errors.append(f"{unit_id} 缺整数 rank")
            continue
        if rank < layer_by_id[layer_id]["rank"]:
            errors.append(f"{unit_id} 的 rank {rank} 低于层 {layer_id} 的下限 {layer_by_id[layer_id]['rank']}")
        for index, layer in enumerate(ordered_layers):
            if layer["id"] == layer_id and index + 1 < len(ordered_layers):
                next_rank = ordered_layers[index + 1]["rank"]
                if rank >= next_rank:
                    errors.append(f"{unit_id} 的 rank {rank} 越过下一层 {ordered_layers[index + 1]['id']} 的下限 {next_rank}")

        if not unit.get("owner"):
            errors.append(f"{unit_id} 缺 owner")
        unit_tiers = unit.get("tier") or []
        if not unit_tiers:
            errors.append(f"{unit_id} 缺 tier")
        for tier in unit_tiers:
            if tier not in tiers:
                errors.append(f"{unit_id} 的 tier 未知：{tier}")
        unit_tests = unit.get("tests") or []
        if not unit_tests:
            errors.append(f"{unit_id} 缺测试桶")
        for bucket in unit_tests:
            if bucket not in buckets:
                errors.append(f"{unit_id} 的测试桶未知：{bucket}")

        for reference in model_refs:
            if reference == unit_id:
                errors.append(f"{unit_id} 引用自身")
                continue
            if reference in by_id:
                target_rank = ranks.get(reference)
                if isinstance(rank, int) and isinstance(target_rank, int) and target_rank >= rank:
                    errors.append(f"{unit_id}(rank={rank}) -> {reference}(rank={target_rank}) 不是严格下层")
            elif reference not in external_names:
                errors.append(f"{unit_id} 引用了未登记的外部程序集：{reference}")

    # 客户端根下所有 asmdef 必须登记，且登记的 asmdef 都落在客户端根下。
    actual_asmdefs = set()
    for relative in CLIENT_ROOTS:
        base = project / relative
        if not base.is_dir():
            errors.append(f"客户端根不存在：{relative}")
            continue
        for path in base.rglob("*.asmdef"):
            actual_asmdefs.add(path.relative_to(project).as_posix())
    registered = set(by_asmdef)
    for relative in sorted(actual_asmdefs - registered):
        errors.append(f"客户端根下存在未登记 asmdef：{relative}")
    for relative in sorted(registered - actual_asmdefs):
        errors.append(f"模型登记了不在客户端根的 asmdef：{relative}")

    # 模块目录必须逐个登记（Modules/<模块> 这一层，不含 Abstractions/SubModules）。
    modules_root = project / "Assets" / "LiteGame" / "Modules"
    if modules_root.is_dir():
        registered_paths = {unit.get("path") for unit in units}
        for directory in sorted(modules_root.iterdir()):
            if not directory.is_dir():
                continue
            relative = directory.relative_to(project).as_posix()
            if relative not in registered_paths:
                errors.append(f"模块目录未登记：{relative}")

    # 收集组：归属唯一、路径存在、落在模块 Content/ 下（例外逐条登记）。
    actual_groups = collect_groups(project)
    owner_by_group: dict[str, str] = {}
    owner_path_by_group: dict[str, str] = {}
    for unit in units:
        for group in unit.get("collectGroups", []) or []:
            if group in owner_by_group:
                errors.append(f"收集组重复归属：{group} -> {owner_by_group[group]} / {unit['id']}")
                continue
            owner_by_group[group] = unit["id"]
            owner_path_by_group[group] = unit.get("path", "")
    exceptions = model.get("collectPathExceptions") or {}
    used_exceptions = set()
    for group, paths in sorted(actual_groups.items()):
        if group not in owner_by_group:
            errors.append(f"收集组未登记到任何模块：{group}")
            continue
        owner_path = owner_path_by_group[group].rstrip("/")
        exception = exceptions.get(group)
        if exception:
            used_exceptions.add(group)
            if exception.get("owner") != owner_by_group[group]:
                errors.append(f"收集组例外归属不符：{group} -> {exception.get('owner')}（登记 {owner_by_group[group]}）")
            if not exception.get("reason"):
                errors.append(f"收集组例外缺依据：{group}")
            continue
        expected = owner_path + "/Content/"
        for path in paths:
            if not path.startswith(expected):
                errors.append(f"{owner_by_group[group]} 的收集组 {group} 路径不在 {expected} 下：{path}")
    for group in sorted(set(owner_by_group) - set(actual_groups)):
        errors.append(f"登记了不存在的收集组：{group}")
    for group in sorted(exceptions):
        if group not in actual_groups:
            errors.append(f"收集组例外登记了不存在的组：{group}")
        elif group not in used_exceptions:
            errors.append(f"收集组例外残留（该组已按模块 Content 路径对齐）：{group}")
    for group, paths in sorted(actual_groups.items()):
        for path in paths:
            if not (project / path).exists():
                errors.append(f"收集组路径不存在：{group} -> {path}")

    # 顶层目录登记。
    top = model.get("topLevel") or {}
    assets = top.get("assets") or {}
    declared_assets = set(assets.get("dirs") or [])
    ignored_assets = set(assets.get("ignored") or [])
    if declared_assets & ignored_assets:
        errors.append("Assets 顶层登记与忽略面重叠")
    actual_top = {path.name for path in (project / "Assets").iterdir() if path.is_dir()}
    visible_top = actual_top - ignored_assets
    for name in sorted(visible_top - declared_assets):
        errors.append(f"Assets 顶层目录未登记：{name}")
    for name in sorted(declared_assets - visible_top):
        errors.append(f"Assets 顶层登记了不存在的目录：{name}")
    litegame_top = set(top.get("liteGame") or [])
    actual_litegame = {path.name for path in (project / "Assets" / "LiteGame").iterdir() if path.is_dir()}
    for name in sorted(actual_litegame - litegame_top):
        errors.append(f"Assets/LiteGame 顶层目录未登记：{name}")
    for name in sorted(litegame_top - actual_litegame):
        errors.append(f"Assets/LiteGame 顶层登记了不存在的目录：{name}")

    # 域清单与允许边（供 domain-matrix.py 读取）。
    domains = model.get("domains") or []
    domain_ids = set()
    for domain in domains:
        domain_id = domain.get("id")
        if not domain_id or domain_id in domain_ids:
            errors.append(f"domain id 缺失或重复：{domain_id}")
            continue
        domain_ids.add(domain_id)
        if not domain.get("role"):
            errors.append(f"domain {domain_id} 缺 role")
        unit_id = "LiteGame.Modules." + ("UI" if domain_id == "Ui" else domain_id)
        if unit_id not in by_id:
            errors.append(f"domain {domain_id} 缺对应模块单元：{unit_id}")
    edges = model.get("domainEdges") or []
    seen_edges = set()
    for edge in edges:
        source, target = edge.get("from"), edge.get("to")
        if source not in domain_ids or target not in domain_ids:
            errors.append(f"域边端点未登记：{source} -> {target}")
        if source == target:
            errors.append(f"域边不能自指：{source}")
        if not edge.get("reason"):
            errors.append(f"域边缺依据：{source} -> {target}")
        key = (source, target)
        if key in seen_edges:
            errors.append(f"域边重复：{source} -> {target}")
        seen_edges.add(key)

    # 改什么→发什么矩阵。
    change_matrix = model.get("changeMatrix") or []
    if not change_matrix:
        errors.append("changeMatrix 不能为空")
    for row in change_matrix:
        if not row.get("change") or not row.get("paths"):
            errors.append(f"changeMatrix 行缺 change/paths：{row.get('change')}")
        for ship in row.get("ship") or []:
            if ship not in tiers:
                errors.append(f"changeMatrix 行 ship 不是 tier：{row.get('change')} -> {ship}")

    # 扫描根：规则集/排除集在 ScanTargets.cs 中真实存在，根路径存在。
    rule_names, exclude_names = scan_rule_names(project)
    scan_targets = model.get("scanTargets") or []
    if not scan_targets:
        errors.append("scanTargets 不能为空")
    seen_targets = set()
    for target in scan_targets:
        root = target.get("root", "")
        if not (project / root).exists():
            errors.append(f"扫描根不存在：{root}")
        if target.get("rules") not in rule_names:
            errors.append(f"扫描规则集未定义：{target.get('rules')}")
        exclude = target.get("exclude")
        if exclude and exclude not in exclude_names:
            errors.append(f"扫描排除集未定义：{exclude}")
        key = (root, target.get("rules"), exclude, bool(target.get("includeEditor", False)))
        if key in seen_targets:
            errors.append(f"扫描目标重复：{key}")
        seen_targets.add(key)
    if "ScanTargetsGenerated.Default" not in read_text(project / SCAN_TARGETS_REL):
        errors.append("ScanTargets.cs 未引用 ScanTargetsGenerated.Default（扫描根必须由模型投影）")

    return errors


def render_legacy_tiers(model: dict) -> str:
    modules = []
    for unit in module_units(model):
        modules.append({
            "id": unit["id"],
            "path": unit["path"],
            "tiers": unit["tier"],
            "collectGroups": unit["collectGroups"],
            "ship": "base",
            "notes": unit["notes"],
        })
    payload = {
        "version": 1,
        "generatedFrom": "arch/units.json",
        "tiers": model["tiers"],
        "modules": modules,
        "changeMatrix": model["changeMatrix"],
    }
    return json.dumps(payload, ensure_ascii=False, indent=2) + "\n"


def cs_string(value: str | None) -> str:
    if value is None:
        return "null"
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def cs_array(values: list[str], indent: int = 12) -> str:
    pad = " " * indent
    return ",\n".join(pad + cs_string(value) for value in values)


def render_scan_generated(model: dict) -> str:
    lines = [GENERATED_HEADER.rstrip("\n"), "namespace Tools.DisciplineScan", "{", "    internal static class ScanTargetsGenerated", "    {"]
    lines += [
        "        internal readonly struct Entry",
        "        {",
        "            internal readonly string Root;",
        "            internal readonly string Rules;",
        "            internal readonly string Exclude;",
        "            internal readonly bool IncludeEditor;",
        "",
        "            internal Entry(string root, string rules, string exclude, bool includeEditor)",
        "            {",
        "                Root = root;",
        "                Rules = rules;",
        "                Exclude = exclude;",
        "                IncludeEditor = includeEditor;",
        "            }",
        "        }",
        "",
        "        internal static readonly Entry[] Default =",
        "        {",
    ]
    for target in model["scanTargets"]:
        lines.append(
            "            new Entry("
            + cs_string(target["root"]) + ", "
            + cs_string(target["rules"]) + ", "
            + cs_string(target.get("exclude")) + ", "
            + ("true" if target.get("includeEditor") else "false") + "),"
        )
    lines += ["        };", ""]
    top = model["topLevel"]
    lines += ["        internal static readonly string[] LiteGameTopLevelDirs =", "        {"]
    lines.append(cs_array(top["liteGame"]) + ",")
    lines += ["        };", "", "        internal static readonly string[] AssetsTopLevelDirs =", "        {"]
    lines.append(cs_array(top["assets"]["dirs"]) + ",")
    lines += ["        };", "", "        internal static readonly string[] AssetsTopLevelIgnored =", "        {"]
    lines.append(cs_array(top["assets"]["ignored"]) + ",")
    lines += ["        };", "    }", "}", ""]
    return "\n".join(lines)


def render_meta(relative: str) -> str:
    guid = uuid5(NAMESPACE_URL, "litegame/arch/" + relative).hex
    return (
        "fileFormatVersion: 2\n"
        f"guid: {guid}\n"
        "MonoImporter:\n"
        "  externalObjects: {}\n"
        "  serializedVersion: 2\n"
        "  defaultReferences: []\n"
        "  executionOrder: 0\n"
        "  icon: {instanceID: 0}\n"
        "  userData: \n"
        "  assetBundleName: \n"
        "  assetBundleVariant: \n"
    )


def write_projection(project: Path, relative: Path, content: str, errors: list[str]) -> None:
    path = project / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    if path.suffix == ".cs":
        meta = path.with_name(path.name + ".meta")
        if not meta.exists():
            meta.write_text(render_meta(relative.as_posix()), encoding="utf-8", newline="\n")
        else:
            check_meta(project, relative, errors)


def check_meta(project: Path, relative: Path, errors: list[str]) -> None:
    meta = project / relative.with_name(relative.name + ".meta")
    if not meta.is_file():
        errors.append(f"生成物缺 .meta：{relative.as_posix()}.meta")
        return
    match = re.search(r"^guid:\s*([0-9a-fA-F]{32})\s*$", read_text(meta), re.MULTILINE)
    if not match:
        errors.append(f"生成物 .meta 缺合法 32 位 guid：{relative.as_posix()}.meta")


def check_generated(project: Path, model: dict) -> list[str]:
    errors: list[str] = []
    expected_legacy = render_legacy_tiers(model)
    legacy = project / LEGACY_TIERS_REL
    if not legacy.is_file():
        errors.append(f"缺旧表只读镜像：{LEGACY_TIERS_REL.as_posix()}（先 --write）")
    elif read_text(legacy) != expected_legacy:
        errors.append(f"旧表只读镜像过期：{LEGACY_TIERS_REL.as_posix()}（重跑 --write）")
    expected_scan = render_scan_generated(model)
    generated = project / SCAN_GENERATED_REL
    if not generated.is_file():
        errors.append(f"缺扫描根投影：{SCAN_GENERATED_REL.as_posix()}（先 --write）")
    elif read_text(generated) != expected_scan:
        errors.append(f"扫描根投影过期：{SCAN_GENERATED_REL.as_posix()}（重跑 --write）")
    check_meta(project, SCAN_GENERATED_REL, errors)
    return errors


def summarize(model: dict) -> str:
    groups = {group for unit in model["units"] for group in unit.get("collectGroups", [])}
    return (
        f"{len(model['units'])} units / {len(model['layers'])} layers / "
        f"{len(groups)} collect groups / {len(model['scanTargets'])} scan targets / "
        f"{len(model['domains'])} domains / {len(model['domainEdges'])} domain edges"
    )


def main(argv=None) -> int:
    configure_stdio()
    parser = argparse.ArgumentParser(description="架构单元模型门禁")
    parser.add_argument("--project-path", default=None)
    parser.add_argument("--write", action="store_true", help="从模型重写 C# 扫描根与旧表镜像")
    parser.add_argument("--check", action="store_true", help="校验模型与投影（默认行为）")
    args = parser.parse_args(argv)
    project = Path(args.project_path).resolve() if args.project_path else repo_root()

    model = load_model(project)
    errors = validate_model(project, model)
    if errors:
        for error in errors:
            fail("quality/arch", error)
        return EXIT_FAIL

    if args.write:
        write_projection(project, LEGACY_TIERS_REL, render_legacy_tiers(model), errors)
        write_projection(project, SCAN_GENERATED_REL, render_scan_generated(model), errors)
        if errors:
            for error in errors:
                fail("quality/arch", error)
            return EXIT_FAIL
        info("quality/arch", "已重写 " + LEGACY_TIERS_REL.as_posix())
        info("quality/arch", "已重写 " + SCAN_GENERATED_REL.as_posix())
        return EXIT_OK

    errors = check_generated(project, model)
    if errors:
        for error in errors:
            fail("quality/arch", error)
        return EXIT_FAIL
    info("quality/arch", "OK: " + summarize(model))
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
