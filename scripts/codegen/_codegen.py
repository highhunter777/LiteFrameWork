# -*- coding: utf-8 -*-
"""Shared single source for the generator toolbox (scripts/codegen/*).

Every generator here follows one form (see the generator toolbox design doc):
  - repo root comes from _common.repo_root(), the single implementation;
  - output goes through info/warn/fail with a `[codegen/<tool>]` prefix;
  - expected failures surface as ONE clean `[codegen/<tool>] FAILED: ...`
    line + exit code 1 -- never a traceback, never a silent no-op;
  - input fingerprints, the artifact signature block and kebab-case module
    loading share one implementation here (`normalize_eol` / `input_digest` /
    `digest_text` / `signature` / `load_module`), so generators and path
    consumers never keep a second copy of those rules.

Import from each tool:  from _codegen import repo_root, info, warn, fail, run_tool
"""

import hashlib
import importlib.util
import os
import sys

SCRIPTS_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if SCRIPTS_DIR not in sys.path:
    sys.path.insert(0, SCRIPTS_DIR)

from _common import fail as _fail, info as _info, repo_root as _repo_root, warn as _warn  # noqa: E402


def repo_root():
    """scripts/codegen -> repo root, delegated to scripts/_common.py."""
    return str(_repo_root())


def info(tool, message):
    _info(f"codegen/{tool}", message)


def warn(tool, message):
    _warn(f"codegen/{tool}", message)


def fail(tool, message):
    return _fail(f"codegen/{tool}", message)


def run_tool(tool, main):
    """Unified execution face: run <main>, convert exceptions to one clean
    [codegen/<tool>] FAILED line + exit 1 (expected-failure contract).

    Direct invocation outside the toolbox is deprecated: unless the process was
    launched by the toolbox (transit env ``CODEGEN_VIA_TOOLBOX=1``) or the tool
    IS the toolbox, one ``[deprecated]`` line on stderr points at
    ``toolbox.py <tool>``. The hint never blocks and never changes the exit code.
    """
    if tool != 'toolbox' and os.environ.get('CODEGEN_VIA_TOOLBOX') != '1':
        print(f'[deprecated] direct invocation of codegen/{tool} is deprecated; '
              f'use: python scripts/codegen/toolbox.py {tool} [args...]',
              file=sys.stderr)
    try:
        code = main()
        sys.exit(0 if code is None else code)
    except SystemExit:
        raise
    except Exception as exc:  # noqa: BLE001 - single clean failure line is the contract
        fail(tool, str(exc))
        sys.exit(1)


def normalize_eol(text):
    """Collapse CRLF/CR to LF for both str and bytes (cross-machine digests)."""
    if isinstance(text, bytes):
        return text.replace(b'\r\n', b'\n').replace(b'\r', b'\n')
    return text.replace('\r\n', '\n').replace('\r', '\n')


def input_digest(paths, root=None):
    """Short input fingerprint: sorted repo-relative path + NUL + EOL-normalized
    content, SHA-256, first 8 hex chars. Directories expand to their files.
    Path order does not matter; line endings do not matter."""
    base = os.path.abspath(str(root)) if root is not None else str(_repo_root())
    entries = []
    for raw in paths:
        rel = str(raw).replace('\\', '/')
        full = os.path.join(base, rel.replace('/', os.sep))
        if os.path.isdir(full):
            for dirpath, dirnames, filenames in os.walk(full):
                dirnames.sort()
                for name in sorted(filenames):
                    deepest = os.path.join(dirpath, name)
                    sub = os.path.relpath(deepest, full).replace('\\', '/')
                    entries.append((rel.rstrip('/') + '/' + sub, deepest))
        else:
            entries.append((rel, full))
    entries.sort(key=lambda item: item[0])
    h = hashlib.sha256()
    for rel, full in entries:
        h.update(rel.encode('utf-8'))
        h.update(b'\x00')
        with open(full, 'rb') as f:
            h.update(normalize_eol(f.read()))
    return h.hexdigest()[:8]


def digest_text(text):
    """Short fingerprint for an in-memory canonical input description (a parsed
    field model, a spec body): EOL-normalized text -> SHA-256 -> first 8 hex."""
    return hashlib.sha256(normalize_eol(text).encode('utf-8')).hexdigest()[:8]


def signature(tool, input_label, digest, regen_args=''):
    """The uniform 3-line artifact signature block every toolbox text artifact
    carries: `toolbox/<tool>` provenance, the input fingerprint, and the regen
    command, closing with '>'. One implementation -- the tests pin this form."""
    return [
        f'// <auto-generated: toolbox/{tool} — DO NOT EDIT',
        f'// input: {input_label} sha256:{digest}',
        f'// regen: python scripts/codegen/toolbox.py {tool}{regen_args}>',
    ]


def load_module(name):
    """Import a generator module by file name (kebab-case module names are not
    importable via import_module; spec loading keeps the path single-source)."""
    filename = os.path.join(os.path.dirname(os.path.abspath(__file__)), name + '.py')
    if not os.path.isfile(filename):
        raise FileNotFoundError(f'codegen module not found: {filename}')
    spec = importlib.util.spec_from_file_location(
        'codegen_loaded_' + name.replace('-', '_'), filename)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module
