#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the runtime page catalog (PageDefinition single artifact).

Inputs:
  - Luban/Data/#uiform.xlsx        (runtime directory source: id/lua_path/prefab/layer/full_screen)
  - Assets/LiteGame/Editor/UiTools/UiPageManifest.json
  - Assets/LiteGame/Editor/UiTools/Contracts/*.contract.json

Output:
  - Assets/LiteClient/UI/Generated/UiPageCatalog.g.cs

The generated file is the only runtime page directory. Contracts/manifest/hash stay
editor-side; runtime code reads PageDefinition via IPageCatalog.

Usage:
  python scripts/codegen/gen-ui-page.py
  python scripts/codegen/gen-ui-page.py --check
"""

import argparse
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from _common import repo_root  # noqa: E402
import _uiform_row  # noqa: E402

ROOT = Path(repo_root())
TOOL = "codegen/ui-page"
DEFAULT_TABLE = ROOT / "Luban" / "Data" / "#uiform.xlsx"
DEFAULT_MANIFEST = ROOT / "Assets" / "LiteGame" / "Editor" / "UiTools" / "UiPageManifest.json"
DEFAULT_CONTRACTS = ROOT / "Assets" / "LiteGame" / "Editor" / "UiTools" / "Contracts"
DEFAULT_OUTPUT = ROOT / "Assets" / "LiteClient" / "UI" / "Generated" / "UiPageCatalog.g.cs"


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description="Generate UiPageCatalog.g.cs")
    parser.add_argument("--table", default=str(DEFAULT_TABLE))
    parser.add_argument("--manifest", default=str(DEFAULT_MANIFEST))
    parser.add_argument("--contracts", default=str(DEFAULT_CONTRACTS))
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT))
    parser.add_argument("--check", action="store_true", help="compare generated bytes with the checked-in file")
    return parser.parse_args(argv)


def read_json(path):
    with open(path, "r", encoding="utf-8-sig") as handle:
        return json.load(handle)


def parse_bool(value):
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() == "true"


def load_pages(manifest_path):
    manifest = read_json(manifest_path)
    by_form = {}
    by_prefab = {}
    for page in manifest.get("pages", []):
        prefab = page.get("prefabPath") or ""
        by_prefab.setdefault(prefab, page)
        for form in page.get("forms", []):
            form_id = int(form.get("formId") or 0)
            if form_id:
                by_form[form_id] = page
    return by_form, by_prefab, manifest


def load_contract(contracts_dir, page):
    path = page.get("contractPath") if page else None
    if not path:
        return []
    full = ROOT / path if not os.path.isabs(path) else Path(path)
    if not full.is_file():
        return []
    contract = read_json(full)
    return contract


def controls_of(contract):
    return contract.get("controls", []) if contract else []


def text_keys_of(contract):
    return contract.get("text", []) if contract else []


def styles_of(contract):
    return contract.get("styles", []) if contract else []


def cache_enum(value):
    value = (value or "Lru").strip()
    if value not in ("Lru", "Resident", "DestroyOnClose"):
        raise ValueError(f"未知 cacheStrategy：{value}")
    return value


def cs_string(value):
    value = "" if value is None else str(value)
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "\\r").replace("\n", "\\n") + '"'


def build_definitions(args):
    wb, ws = _uiform_row.load_workbook(Path(args.table))
    by_form, by_prefab, manifest = load_pages(Path(args.manifest))
    contracts_dir = Path(args.contracts)
    definitions = []
    warnings = []

    for _, values in _uiform_row.data_rows(ws):
        form_id = int(values[_uiform_row.COL_ID - 1] or 0)
        if form_id <= 0:
            continue
        prefab = str(values[_uiform_row.COL_PREFAB - 1] or "").strip()
        lua_path = str(values[_uiform_row.COL_LUA - 1] or "").strip()
        layer = int(values[_uiform_row.COL_LAYER - 1] or 0)
        full_screen = parse_bool(values[_uiform_row.COL_FULL - 1])
        prefab_path = "Assets/" + prefab
        page = by_form.get(form_id) or by_prefab.get(prefab_path)
        if page is None:
            raise ValueError(f"tbuiform id={form_id} 未在 UiPageManifest 登记（prefab={prefab_path}）")
        if page.get("luaPath") is not None and str(page.get("luaPath")) != lua_path:
            warnings.append(f"id={form_id} lua_path 表/清单不一致：{lua_path!r} vs {page.get('luaPath')!r}")
        contract = load_contract(contracts_dir, page)
        if page.get("contractPath") and not contract:
            warnings.append(f"id={form_id} 契约缺失：{page.get('contractPath')}（按空绑定表生成）")
        name = page.get("name") or Path(prefab).stem
        cache = cache_enum(page.get("cacheStrategy"))
        definitions.append({
            "id": form_id,
            "name": name,
            "location": prefab_path,
            "lua": lua_path,
            "layer": layer,
            "full": full_screen,
            "cache": cache,
            "controls": controls_of(contract),
            "text": text_keys_of(contract),
            "styles": styles_of(contract),
        })

    # 清单中的每个已登记 form 必须能落成定义——防止清单/表单向漂移。
    table_ids = {item["id"] for item in definitions}
    for page in manifest.get("pages", []):
        for form in page.get("forms", []):
            form_id = int(form.get("formId") or 0)
            if form_id and form_id not in table_ids:
                raise ValueError(f"UiPageManifest 的 formId={form_id} 不在 #uiform 表中（{page.get('name')}）")

    definitions.sort(key=lambda item: item["id"])
    return definitions, warnings


def render(definitions):
    lines = [
        "// <auto-generated: scripts/codegen/gen-ui-page.py —— DO NOT EDIT。",
        "// 源：#uiform + UiPageManifest + Contracts；重跑 python scripts/codegen/gen-ui-page.py；",
        "// 运行时唯一页面目录（PageDefinition）；contract/manifest/hash 不进运行时。>",
        "using System;",
        "using System.Collections.Generic;",
        "",
        "namespace LiteClient.UI",
        "{",
        "    /// <summary>生成的页面目录（PageDefinition 单制品）；运行时经 IPageCatalog 取件。</summary>",
        "    public sealed class UiPageCatalog : IPageCatalog",
        "    {",
        "        /// <summary>全部页面定义（按 Id 升序；工具/注册表填充可用）。</summary>",
        "        public static readonly PageDefinition[] All = new PageDefinition[]",
        "        {",
    ]
    for item in definitions:
        lines.append("            new PageDefinition")
        lines.append("            {")
        lines.append(f"                Id = {item['id']},")
        lines.append(f"                Name = {cs_string(item['name'])},")
        lines.append(f"                Location = {cs_string(item['location'])},")
        lines.append(f"                LuaPath = {cs_string(item['lua'])},")
        lines.append(f"                Layer = {item['layer']},")
        lines.append(f"                FullScreen = {'true' if item['full'] else 'false'},")
        lines.append(f"                CacheStrategy = UICacheStrategy.{item['cache']},")
        if item["controls"]:
            entries = []
            for c in item["controls"]:
                entries.append(
                    "new PageControlDefinition("
                    + cs_string(c.get("bindName"))
                    + ", " + cs_string(c.get("nodePath"))
                    + ", " + cs_string(c.get("type"))
                    + ", " + cs_string(c.get("kind"))
                    + ", " + ("true" if c.get("required") else "false") + ")"
                )
            lines.append("                Controls = new PageControlDefinition[]")
            lines.append("                {")
            for entry in entries:
                lines.append("                    " + entry + ",")
            lines.append("                },")
        if item["text"]:
            entries = []
            for t in item["text"]:
                entries.append(
                    "new PageTextKeyDefinition("
                    + cs_string(t.get("nodePath")) + ", "
                    + cs_string(t.get("key")) + ", "
                    + str(int(t.get("args") or 0)) + ")"
                )
            lines.append("                TextKeys = new PageTextKeyDefinition[]")
            lines.append("                {")
            for entry in entries:
                lines.append("                    " + entry + ",")
            lines.append("                },")
        if item["styles"]:
            entries = []
            for s in item["styles"]:
                entries.append(
                    "new PageStyleRefDefinition("
                    + cs_string(s.get("nodePath")) + ", "
                    + cs_string(s.get("role")) + ", "
                    + cs_string(s.get("token")) + ")"
                )
            lines.append("                StyleRefs = new PageStyleRefDefinition[]")
            lines.append("                {")
            for entry in entries:
                lines.append("                    " + entry + ",")
            lines.append("                },")
        lines.append("            },")
    lines.extend([
        "        };",
        "",
        "        private static readonly Dictionary<int, PageDefinition> ById = BuildIndex();",
        "",
        "        /// <summary>进程级只读实例（生成的目录无可变状态）。</summary>",
        "        public static UiPageCatalog Instance { get; } = new UiPageCatalog();",
        "",
        "        private static Dictionary<int, PageDefinition> BuildIndex()",
        "        {",
        "            var byId = new Dictionary<int, PageDefinition>(All.Length);",
        "            foreach (PageDefinition page in All)",
        "            {",
        "                if (page == null) throw new InvalidOperationException(\"UiPageCatalog 含空页面定义\");",
        "                if (byId.ContainsKey(page.Id)) throw new InvalidOperationException(\"UiPageCatalog 页面 Id 重复：\" + page.Id);",
        "                byId.Add(page.Id, page);",
        "            }",
        "            return byId;",
        "        }",
        "",
        "        public PageDefinition Get(int id)",
        "        {",
        "            if (!ById.TryGetValue(id, out PageDefinition page))",
        "                throw new KeyNotFoundException(\"页面目录无此 Id：\" + id + \"——核对 #uiform/UiPageManifest 并重跑 gen-ui-page.py\");",
        "            return page;",
        "        }",
        "    }",
        "}",
        "",
    ])
    return "\n".join(lines)


def main(argv=None):
    args = parse_args(argv)
    try:
        definitions, warnings = build_definitions(args)
        text = render(definitions)
    except Exception as exc:  # noqa: BLE001 - CLI diagnosis
        print(f"[ui-page] FAIL: {exc}", file=sys.stderr)
        return 1

    for warning in warnings:
        print(f"[ui-page] WARN: {warning}", file=sys.stderr)

    output = Path(args.output)
    if args.check:
        current = output.read_text(encoding="utf-8") if output.is_file() else ""
        if current != text:
            print(f"[ui-page] CHECK FAILED: {output} 过旧；重跑 python scripts/codegen/gen-ui-page.py", file=sys.stderr)
            return 1
        print(f"[ui-page] CHECK OK: {len(definitions)} pages")
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="utf-8", newline="\n")
    print(f"[ui-page] wrote {output} ({len(definitions)} pages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
