#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the runtime page catalog (PageDefinition single artifact).

Inputs:
  - Luban/Data/#uiform.xlsx        (runtime directory source: id/prefab/layer/full_screen/
                                    cache_strategy —页面元数据唯一来源)
  - every page prefab the table lists (controls / text / styles, read by
                                    _prefab_page_reader.py; the page name is that
                                    prefab's file stem)

Output:
  - Assets/LiteGame/Modules/UI/Generated/UIPageCatalog.g.cs
  - Assets/LiteGame/Modules/UI/Generated/PageIds.g.cs   (page id constants; same source, same run)

The generated file is the only runtime page directory; runtime code reads
PageDefinition via IPageCatalog. Neither UIPageManifest.json nor the contracts
are read here: the table is the only metadata source and _prefab_page_reader.py is
the contract-free bind-surface reader.

Usage:
  python scripts/codegen/toolbox.py ui-page [--check]     # supported entry
  python scripts/codegen/gen-ui-page.py [--check]         # deprecated (prints [deprecated])
"""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from collections import Counter  # noqa: E402

from _common import repo_root  # noqa: E402
from _codegen import fail, info, input_digest, run_tool, signature  # noqa: E402
import _uiform_row  # noqa: E402
import _prefab_page_reader  # noqa: E402

ROOT = Path(repo_root())
TOOL = "ui-page"
DEFAULT_TABLE = ROOT / "Luban" / "Data" / "#uiform.xlsx"
DEFAULT_OUTPUT = ROOT / "Assets" / "LiteGame" / "Modules" / "UI" / "Generated" / "UIPageCatalog.g.cs"
DEFAULT_IDS_OUTPUT = ROOT / "Assets" / "LiteGame" / "Modules" / "UI" / "Generated" / "PageIds.g.cs"
# Generated page names become C# symbol/const names: no fallback, an unnameable
# prefab fails the run instead of emitting uncompilable code.
PAGE_NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def _rel(path):
    """Repo-relative POSIX path for a declared constant."""
    return Path(path).resolve().relative_to(ROOT).as_posix()


def _fingerprint_entry(path):
    """Digest entry for one input: repo-relative POSIX (portable head), falling
    back to the absolute path only for inputs the caller placed outside the repo."""
    resolved = Path(path).resolve()
    try:
        return resolved.relative_to(ROOT).as_posix()
    except ValueError:
        return resolved.as_posix()


def build_head(args, prefab_paths):
    """The uniform signature block; the fingerprint covers the table, the built-in
    component map and every page prefab actually read."""
    entries = [
        _fingerprint_entry(args.table),
        _fingerprint_entry(_prefab_page_reader.BUILTIN_MAP_PATH),
    ]
    entries.extend(sorted(_fingerprint_entry(path) for path in prefab_paths))
    label = "%s + %s + %d page prefabs" % (entries[0], entries[1], len(prefab_paths))
    return signature("ui-page", label, input_digest(entries))


def table_rows(table=None):
    """Every usable #uiform row: id / prefab path / layer / full_screen / cache."""
    wb, ws = _uiform_row.load_workbook(Path(table or DEFAULT_TABLE))
    rows = []
    for _, values in _uiform_row.data_rows(ws):
        form_id = int(values[_uiform_row.COL_ID - 1] or 0)
        if form_id <= 0:
            continue
        prefab = str(values[_uiform_row.COL_PREFAB - 1] or "").strip()
        rows.append({
            "id": form_id,
            "prefab": "Assets/" + prefab,
            "layer": int(values[_uiform_row.COL_LAYER - 1] or 0),
            "full": parse_bool(values[_uiform_row.COL_FULL - 1]),
            "cache": _uiform_row.cache_strategy_name(values[_uiform_row.COL_CACHE - 1]),
        })
    return rows


def page_prefab_paths():
    """Every prefab path the table lists (the reader's real input set)."""
    return sorted({row["prefab"] for row in table_rows()})


def path_report():
    """Declared inputs/output derived from the DEFAULT_* constants."""
    entries = [
        {"path": _rel(DEFAULT_TABLE), "kind": "input"},
        {"path": _rel(_prefab_page_reader.BUILTIN_MAP_PATH), "kind": "input"},
    ]
    entries.extend({"path": path, "kind": "input"} for path in page_prefab_paths())
    entries.extend([
        {"path": _rel(DEFAULT_OUTPUT), "kind": "output"},
        {"path": _rel(DEFAULT_IDS_OUTPUT), "kind": "output"},
    ])
    return entries


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description="Generate UIPageCatalog.g.cs")
    parser.add_argument("--table", default=str(DEFAULT_TABLE))
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT))
    parser.add_argument("--ids-output", default="",
                        help="page id constants path (default: PageIds.g.cs next to --output)")
    parser.add_argument("--check", action="store_true", help="compare generated bytes with the checked-in file")
    return parser.parse_args(argv)


def parse_bool(value):
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() == "true"


def cs_string(value):
    value = "" if value is None else str(value)
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "\\r").replace("\n", "\\n") + '"'


def build_definitions(args):
    reader = _prefab_page_reader.PageReader(ROOT)
    read_cache = {}
    definitions = []
    prefab_paths = []

    for row in table_rows(args.table):
        prefab_path = row["prefab"]
        page_read = read_cache.get(prefab_path)
        if page_read is None:
            page_read = reader.read(str(ROOT / prefab_path))
            read_cache[prefab_path] = page_read
            prefab_paths.append(prefab_path)
        name = Path(prefab_path).stem
        if not PAGE_NAME_RE.match(name):
            raise ValueError(
                f"prefab 文件名无法派生成页面名（需 C# 标识符，stem={name!r}）：{prefab_path}")
        definitions.append({
            "id": row["id"],
            "name": name,
            "location": prefab_path,
            "layer": row["layer"],
            "full": row["full"],
            "cache": row["cache"],
            "controls": page_read.controls,
            "text": page_read.text,
            "styles": page_read.styles,
        })

    definitions.sort(key=lambda item: item["id"])
    return definitions, sorted(prefab_paths)


def render_ids(definitions, head):
    """Page id constants: the compile-time counterpart of the string page keys."""
    seen = Counter(item["name"] for item in definitions)
    lines = head + [
        "namespace LiteGame.Modules.UI",
        "{",
        "    /// <summary>生成的页面 id 常量（#uiform 单源）：页面流与模态登记按 id 寻址，不拼字符串键。</summary>",
        "    public static class PageIds",
        "    {",
    ]
    for item in definitions:
        name = item["name"]
        const = name if seen[name] == 1 else "%s_%d" % (name, item["id"])
        lines.append("        /// <summary>%s（id %d）</summary>" % (name, item["id"]))
        lines.append("        public const int %s = %d;" % (const, item["id"]))
    lines.extend([
        "    }",
        "}",
        "",
    ])
    return "\n".join(lines)


def render(definitions, head):
    lines = head + [
        "using System;",
        "using System.Collections.Generic;",
        "using LiteFramework.UI;",
        "",
        "namespace LiteGame.Modules.UI",
        "{",
        "    /// <summary>生成的页面目录（PageDefinition 单制品）；运行时经 IPageCatalog 取件。</summary>",
        "    public sealed class UIPageCatalog : IPageCatalog",
        "    {",
        "        /// <summary>全部页面定义（按 Id 升序；工具/注册表填充可用）。</summary>",
        "        public static readonly PageDefinition[] All = new PageDefinition[]",
        "        {",
    ]
    for item in definitions:
        lines.append("            new PageDefinition")
        lines.append("            {")
        lines.append(f"                Id = {item['id']},")
        lines.append(f"                Name = {cs_string(item['name'])},")
        lines.append(f"                Location = {cs_string(item['location'])},")
        # 页面逻辑＝prefab 自带 C# 组件（无逻辑路径字段）
        lines.append(f"                Layer = {item['layer']},")
        lines.append(f"                FullScreen = {'true' if item['full'] else 'false'},")
        lines.append(f"                CacheStrategy = UICacheStrategy.{item['cache']},")
        if item["controls"]:
            entries = []
            for c in item["controls"]:
                entries.append(
                    "new PageControlDefinition("
                    + cs_string(c.get("bindName"))
                    + ", " + cs_string(c.get("nodePath"))
                    + ", " + cs_string(c.get("type"))
                    + ", " + cs_string(c.get("kind"))
                    + ", " + ("true" if c.get("required") else "false") + ")"
                )
            lines.append("                Controls = new PageControlDefinition[]")
            lines.append("                {")
            for entry in entries:
                lines.append("                    " + entry + ",")
            lines.append("                },")
        if item["text"]:
            entries = []
            for t in item["text"]:
                entries.append(
                    "new PageTextKeyDefinition("
                    + cs_string(t.get("nodePath")) + ", "
                    + cs_string(t.get("key")) + ", "
                    + str(int(t.get("args") or 0)) + ")"
                )
            lines.append("                TextKeys = new PageTextKeyDefinition[]")
            lines.append("                {")
            for entry in entries:
                lines.append("                    " + entry + ",")
            lines.append("                },")
        if item["styles"]:
            entries = []
            for s in item["styles"]:
                entries.append(
                    "new PageStyleRefDefinition("
                    + cs_string(s.get("nodePath")) + ", "
                    + cs_string(s.get("role")) + ", "
                    + cs_string(s.get("token")) + ")"
                )
            lines.append("                StyleRefs = new PageStyleRefDefinition[]")
            lines.append("                {")
            for entry in entries:
                lines.append("                    " + entry + ",")
            lines.append("                },")
        lines.append("            },")
    lines.extend([
        "        };",
        "",
        "        private static readonly Dictionary<int, PageDefinition> ById = BuildIndex();",
        "",
        "        /// <summary>进程级只读实例（生成的目录无可变状态）。</summary>",
        "        public static UIPageCatalog Instance { get; } = new UIPageCatalog();",
        "",
        "        private static Dictionary<int, PageDefinition> BuildIndex()",
        "        {",
        "            var byId = new Dictionary<int, PageDefinition>(All.Length);",
        "            foreach (PageDefinition page in All)",
        "            {",
        "                if (page == null) throw new InvalidOperationException(\"UIPageCatalog 含空页面定义\");",
        "                if (byId.ContainsKey(page.Id)) throw new InvalidOperationException(\"UIPageCatalog 页面 Id 重复：\" + page.Id);",
        "                byId.Add(page.Id, page);",
        "            }",
        "            return byId;",
        "        }",
        "",
        "        public PageDefinition Get(int id)",
        "        {",
        "            if (!ById.TryGetValue(id, out PageDefinition page))",
        "                throw new KeyNotFoundException(\"页面目录无此 Id：\" + id + \"——核对 #uiform 并重跑 gen-ui-page.py\");",
        "            return page;",
        "        }",
        "    }",
        "}",
        "",
    ])
    return "\n".join(lines)


def main(argv=None):
    args = parse_args(argv)
    try:
        definitions, prefab_paths = build_definitions(args)
        head = build_head(args, prefab_paths)
        text = render(definitions, head)
        ids_text = render_ids(definitions, head)
    except Exception as exc:  # noqa: BLE001 - CLI diagnosis
        return fail(TOOL, str(exc))

    output = Path(args.output)
    ids_output = Path(args.ids_output) if args.ids_output else output.parent / DEFAULT_IDS_OUTPUT.name
    if args.check:
        current = output.read_text(encoding="utf-8") if output.is_file() else ""
        if current != text:
            info(TOOL, f"CHECK FAILED: {output} 过旧；重跑 python scripts/codegen/toolbox.py ui-page")
            return 1
        current_ids = ids_output.read_text(encoding="utf-8") if ids_output.is_file() else ""
        if current_ids != ids_text:
            info(TOOL, f"CHECK FAILED: {ids_output} 过旧；重跑 python scripts/codegen/toolbox.py ui-page")
            return 1
        info(TOOL, f"CHECK OK: {len(definitions)} pages")
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    _write_preserving_eol(output, text)
    ids_output.parent.mkdir(parents=True, exist_ok=True)
    _write_preserving_eol(ids_output, ids_text)
    info(TOOL, f"wrote {output} + {ids_output} ({len(definitions)} pages)")
    return 0


def _write_preserving_eol(path, text):
    """Keep the checkout's line endings (git autocrlf may hand us CRLF); a fresh
    LF file stays LF, so regeneration is byte-stable on every platform."""
    newline = "\n"
    if path.is_file() and b"\r\n" in path.read_bytes():
        newline = "\r\n"
    path.write_text(text, encoding="utf-8", newline=newline)


if __name__ == "__main__":
    run_tool(TOOL, main)